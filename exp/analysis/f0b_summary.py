"""F0b validation (registration amendment 18): does the revision fast path reproduce B1-H1?

    python -m exp.analysis.f0b_summary [--submitted results/sprint/_hf] [--revision <RESULTS_DIR or local HF mirror>]
                                       [--out results/eacl_revision_1/F0b]

Submitted: the B1 main arms (own template, seeds 0-19) under <submitted>/runs/B1/{rlvr,dpo}__sys-own/<hash>/.
Revision:  the F0b_B1 shards under <revision>/runs/eacl_revision_1/F0b_B1/{rlvr,dpo}__sys-own/<hash>/ (or, while
           running, the gen progress files under <revision>/eacl_revision_1/F0b_B1/).
B1-H1 is computed with exp.analysis.b1_summary's own per_arm / paired (per wording, mean of paired differences,
percentile bootstrap 10,000, seed 20261024, per-label generator; Wilcoxon).

Registered pass rule (amendment 18, F0b), all of:
  1. the reproduced B1-H1 point estimate lies inside the submitted interval [+0.131, +0.233];
  2. per arm (RLVR, DPO), the reproduced valid rate (valid generations / generations) is at or above the 95% Wilson
     lower bound of the submitted valid rate (one-sided; changed Nov 27, before any F0b generation ran, because the
     submitted RLVR 960/960 gave a [1, 1] bootstrap interval that one invalid generation would fail; registration
     doc, note under amendment 18). RLVR 960/960 -> at most 3 invalid of 960; DPO 959/960 -> at most 5;
  3. per arm, the reproduced mean think tokens lie inside the submitted mean think tokens' bootstrap interval.
Think tokens use the same unit as B1-H1: per wording (mean over its generations), then the mean over wordings,
bootstrapped over wordings. The throughput benchmark (part bench) is summarised from its shard metadata.
"""
import argparse
import collections
import json
from pathlib import Path

import numpy as np

from . import b1_summary as B1S
from . import sprint_common as SC

SUBMITTED_H1 = (0.181, 0.131, 0.233)


def _arms(root, job_glob, engine=None):
    """Main-arm B1 shards under runs/<job_glob>/. engine (revision runs only): keep only shards whose recorded
    engine is that harness.ENGINES variant, so runs of different engine variants are never mixed."""
    import pyarrow.parquet as pq
    from .. import harness as H
    from ..store import read_metadata
    out = {}
    for f in sorted(Path(root).glob(f"runs/{job_glob}/*__sys-own/*/shard_000.parquet")):
        t = pq.read_table(f)
        if engine is not None:
            rec = read_metadata(t)["config"].get("engine") or {}
            if {k: rec.get(k) for k in H.engine_args(engine)} != H.engine_args(engine):
                continue
        rows = t.to_pylist()
        gen = {f"{r['id']}|{r['seed']}": r for r in rows}
        ck, sysm, kind = B1S.arm_label(f"{f.parts[-3]}__{f.parts[-2]}", gen)
        if kind.startswith("main"):
            out[ck] = gen
    return out


def _progress_arms(root):
    out = {}
    for d in sorted((Path(root) / "eacl_revision_1" / "F0b_B1").glob("*__sys-own__*")):
        g = B1S.read_progress(d / "gen_shard0of1.csv")
        if g:
            out[d.name.split("__")[0]] = g
    return out


def valid_count(gen):
    k = sum(1 for r in gen.values() if r["status"] == "valid" and r.get("answer_strict") is not None)
    return k, len(gen)


def per_wording(gen):
    valid, think = collections.defaultdict(list), collections.defaultdict(list)
    for r in gen.values():
        ok = r["status"] == "valid" and r.get("answer_strict") is not None
        valid[r["id"]].append(1.0 if ok else 0.0)
        t = r.get("think_tokens")
        if t is not None:
            think[r["id"]].append(float(t))
    return ({i: float(np.mean(v)) for i, v in valid.items()}, {i: float(np.mean(v)) for i, v in think.items()})


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--submitted", default=str(B1S.ROOT / "results" / "sprint" / "_hf"))
    ap.add_argument("--revision", required=True)
    ap.add_argument("--out", default=str(B1S.ROOT / "results" / "eacl_revision_1" / "F0b"))
    ap.add_argument("--engine", default="fast", help="engine variant of the revision arms to compare (harness.ENGINES)")
    a = ap.parse_args(argv)
    sub = _arms(a.submitted, "B1")
    rev = _arms(a.revision, "eacl_revision_1/F0b_B1", engine=a.engine) or _progress_arms(a.revision)
    L = ["# F0b: fast generation path, B1-H1 reproduction", "",
         "Registration: amendment 18 (F0b). Generated by `exp/analysis/f0b_summary.py`.", "",
         f"Revision arms: engine variant `{a.engine}`.", ""]
    checks = []
    if {"rlvr", "dpo"} <= set(rev) and {"rlvr", "dpo"} <= set(sub):
        s_ext = {c: B1S.per_arm(sub[c], {})["ext_w"] for c in ("rlvr", "dpo")}
        r_ext = {c: B1S.per_arm(rev[c], {})["ext_w"] for c in ("rlvr", "dpo")}
        s_h1 = SC.paired(s_ext["rlvr"], s_ext["dpo"], "B1|H1")
        r_h1 = SC.paired(r_ext["rlvr"], r_ext["dpo"], "B1|H1")
        ok1 = SUBMITTED_H1[1] <= r_h1["mean"] <= SUBMITTED_H1[2]
        checks.append(ok1)
        L += ["## B1-H1: RLVR − DPO sampled P(extreme), per wording", "",
              "| | estimate [95% CI] |", "|---|---|",
              f"| submitted (recomputed from the stored shards) | {SC.fmt(s_h1)} |",
              f"| submitted (as reported) | +0.181 [+0.131, +0.233] |",
              f"| fast path | {SC.fmt(r_h1)} |", "",
              f"- Rule 1, point estimate inside [+0.131, +0.233]: **{'pass' if ok1 else 'FAIL'}** ({r_h1['mean']:+.3f}).", ""]
        L += ["## Per arm: valid rate and mean think tokens (per wording, then mean)", "",
              "| arm | generations (submitted / fast) | valid, submitted [95% Wilson lower bound] | valid, fast | "
              "think tokens, submitted [95% CI] | think tokens, fast | rule 2 | rule 3 |", "|---|---|---|---|---|---|---|---|"]
        for c in ("rlvr", "dpo"):
            _, stt = per_wording(sub[c])
            _, rtt = per_wording(rev[c])
            (ks, ns), (kf, nf) = valid_count(sub[c]), valid_count(rev[c])
            vlo = B1S.wilson(ks, ns)[0]
            tm, tlo, thi = SC.ci_mean(list(stt.values()), f"F0b|think|{c}")
            rtm = float(np.mean(list(rtt.values()))) if rtt else float("nan")
            ok2, ok3 = nf > 0 and kf / nf >= vlo, tlo <= rtm <= thi
            checks += [ok2, ok3]
            L.append(f"| {c.upper()} | {ns} / {nf} | {ks}/{ns} = {ks / ns:.4f} [{vlo:.4f}] | {kf}/{nf} = {kf / max(nf, 1):.4f} | "
                     f"{tm:.0f} [{tlo:.0f}, {thi:.0f}] | {rtm:.0f} | {'pass' if ok2 else 'FAIL'} | {'pass' if ok3 else 'FAIL'} |")
        L.append("")
    else:
        L += [f"Not computable yet: submitted arms {sorted(sub)}, revision arms {sorted(rev)} (need rlvr and dpo).", ""]
    bench = sorted(Path(a.revision).glob("runs/eacl_revision_1/F0b/bench__*/*/shard_000.parquet"))
    if bench:
        import pyarrow.parquet as pq
        from ..store import read_metadata
        t = pq.read_table(bench[-1])
        meta = {k: (json.loads(v) if k in ("tokens", "wall_s", "tok_per_s", "cap_hit") else v)
                for k, v in read_metadata(t).items()}
        rows = t.to_pylist()
        n = len(rows)
        L += ["## Throughput at 32,768 (RLVR, AIME 2024 + 2025, 4 samples, not scored)", "",
              f"- Generations: {n}; tokens: {meta.get('tokens')}; wall: {(meta.get('wall_s') or 0) / 3600:.2f} h; "
              f"**{(meta.get('tok_per_s') or 0):.0f} tokens/s**.",
              f"- Cap hits at 32,768: {meta.get('cap_hit')}/{n} = {meta.get('cap_hit', 0) / max(n, 1):.3f}.",
              f"- Mean tokens per generation: {np.mean([r['n_tokens'] for r in rows]):.0f}.", ""]
    if checks:
        L += ["## Verdict", "", f"**F0b validation: {'PASS' if all(checks) else 'FAIL'}** "
              f"({sum(checks)}/{len(checks)} registered checks pass)."
              + ("" if all(checks) else " Per amendment 18 the fast path is not used; the cause is investigated and "
                 "reported to the PI first."), ""]
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
