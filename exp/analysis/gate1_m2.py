"""Gate 1 (b): M2 on the same traces, RLVR scorer vs DPO scorer (exploratory; registered M2-H1..H5 are in m2_summary).

    python -m exp.analysis.gate1_m2 [--dir results/sprint/M2/partial] [--out results/sprint/M2/gate1_m2.md]

1. P(</think> starts here) at think-block sentence ends (p_close_at_sent, amendment 2), RLVR scorer - DPO scorer,
   per component (A, D) x trace source (RLVR-, DPO-, SFT-written traces); with and without the sentence end at the
   realised close. Units and statistics as m2_summary (A: wording; D: base item; paired; bootstrap 10k, seed 20261024).
2. Stopping-hazard counterfactual on A. For each valid RLVR-written A trace, the DPO scorer's p_close at each of the
   trace's non-final sentence ends is used as a per-sentence stopping hazard; the expected think length if the trace
   had stopped with that hazard is E = sum_k S_k h_k pos_k + S_end * L (S_k = survival before sentence k, pos_k the
   think-token position of sentence end k, L the realised think length). The same with the RLVR scorer's own hazard
   is the check (should return ~L). Share of the A length gap a lower stopping hazard alone predicts =
   mean_w(L_rlvr - E_dpo-hazard) / mean_w(L_rlvr - L_dpo), with L_dpo from valid DPO-written traces of the same
   wording; bootstrap over wordings.
3. If the --kl-detail pair output exists (<dir>/pair_rlvr_dpo_kldetail/), KL(RLVR || DPO) by relative position in the
   think block (20 bins) and the top 30 tokens by total KL, for A and D on RLVR-written traces.
"""
import argparse
import collections
from pathlib import Path

import numpy as np

from .m2_summary import DI, load, unit, trace_value, paired

ROOT = Path(__file__).resolve().parents[2]


def units(rows, comp, tc, fn):
    acc = collections.defaultdict(list)
    for r in rows.values():
        if r.get("trace_ckpt") != tc or r["component"] != comp or r.get("status") != "valid" or "skipped" in r:
            continue
        x = fn(r)
        if x is not None:
            acc[unit(r)].append(x)
    return {u: float(np.mean(v)) for u, v in acc.items()}


def fmt_ci(est, ci, nd=6):
    return f"{est:+.{nd}g} [{ci[0]:+.{nd}g}, {ci[1]:+.{nd}g}]"


def counterfactual_len(row_h, row_own):
    """Expected think length of the trace in row_own if it stopped with the hazard in row_h (same trace, same positions)."""
    te, L = row_own.get("think_end_tok"), row_own.get("n_think_pos")
    pos, h = row_h.get("sent_next_tok") or [], row_h.get("p_close_at_sent") or []
    if te is None or L is None:
        return None
    S, E = 1.0, 0.0
    for k, x in zip(pos, h):
        if k == te:
            continue
        E += S * x * k
        S *= 1.0 - x
    return E + S * L


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(ROOT / "results/sprint/M2/partial"))
    ap.add_argument("--out", default=str(ROOT / "results/sprint/M2/gate1_m2.md"))
    a = ap.parse_args(argv)
    S = load(a.dir)
    R, D = S["rlvr"], S["dpo"]
    L = ["# Gate 1 (b): M2, RLVR scorer vs DPO scorer on the same traces", "",
         "Generated by `exp/analysis/gate1_m2.py` (exploratory). P_close = P(`</think>` starts here) at think-block "
         "sentence ends (amendment 2). Paired RLVR-scorer - DPO-scorer per unit (A: wording, D: base item), mean "
         "[95% bootstrap CI], Wilcoxon p. Valid traces only.", "",
         "## 1. P_close at sentence ends, by component and trace source", "",
         "| component | trace source | n units | RLVR scorer | DPO scorer | RLVR - DPO, all sentence ends | RLVR - DPO, realised close excluded | ratio DPO/RLVR (excl.) |",
         "|---|---|---|---|---|---|---|---|"]
    for comp in "AD":
        for tc in ("rlvr", "dpo", "sft"):
            res = []
            for drop in (False, True):
                fa = units(R, comp, tc, lambda r: trace_value(r, "p_close", drop))
                fb = units(D, comp, tc, lambda r: trace_value(r, "p_close", drop))
                res.append(paired(fa, fb, f"gate1|close|{comp}|{tc}|{drop}"))
            p0, p1 = res
            L.append(f"| {comp} | {tc.upper()} | {p0['n']} | {p0['a']:.3g} | {p0['b']:.3g} | "
                     f"{fmt_ci(p0['mean'], p0['ci'], 3)} (p={p0['p']:.2g}) | {fmt_ci(p1['mean'], p1['ci'], 3)} (p={p1['p']:.2g}) | "
                     f"{p1['b'] / p1['a']:.1f}x |")

    # ---- 2. stopping-hazard counterfactual (A, RLVR-written traces)
    L += ["", "## 2. How much of the A length gap does a lower stopping hazard alone predict?", ""]
    E_d, E_r, L_r, L_d = (collections.defaultdict(list) for _ in range(4))
    for k, r in R.items():
        if r.get("trace_ckpt") != "rlvr" or r["component"] != "A" or r.get("status") != "valid" or k not in D:
            continue
        ed, er = counterfactual_len(D[k], r), counterfactual_len(r, r)
        if ed is None:
            continue
        E_d[unit(r)].append(ed)
        E_r[unit(r)].append(er)
        L_r[unit(r)].append(r["n_think_pos"])
    for k, r in D.items():
        if r.get("trace_ckpt") == "dpo" and r["component"] == "A" and r.get("status") == "valid" and r.get("think_end_tok") is not None:
            L_d[unit(r)].append(r["n_think_pos"])
    ws = sorted(set(E_d) & set(L_d))
    m = lambda dd: np.array([np.mean(dd[w]) for w in ws])  # noqa: E731
    lr, ld, ed, er = m(L_r), m(L_d), m(E_d), m(E_r)
    gap, cut = lr - ld, lr - ed
    idx = DI.make_rng("gate1|hazard_share").integers(0, len(ws), size=(DI.N_BOOT, len(ws)))
    share_b = cut[idx].mean(1) / gap[idx].mean(1)
    L += [f"Wordings with valid RLVR- and DPO-written A traces: {len(ws)}.", "",
          "| quantity (think tokens, mean over wordings) | value |", "|---|---|",
          f"| RLVR-written traces, realised think length | {lr.mean():.0f} |",
          f"| DPO-written traces, realised think length | {ld.mean():.0f} |",
          f"| A length gap (RLVR - DPO) | {gap.mean():.0f} |",
          f"| RLVR traces stopped with the RLVR scorer's own hazard (check, should be ~realised) | {er.mean():.0f} |",
          f"| RLVR traces stopped with the DPO scorer's hazard | {ed.mean():.0f} |",
          f"| expected tokens cut by DPO's hazard | {cut.mean():.0f} |",
          f"| **share of the gap predicted by the hazard alone** | **{cut.mean() / gap.mean():.3f}** "
          f"[{np.percentile(share_b, 2.5):.3f}, {np.percentile(share_b, 97.5):.3f}] |"]

    # ---- 3. KL detail (optional)
    kd = S.get("pair_rlvr_dpo_kldetail")
    L += ["", "## 3. KL(RLVR || DPO) per position and the tokens carrying it", ""]
    if not kd:
        L.append("The `--kl-detail` pair output is not available yet (M2 pair step with `--kl-detail`, lane N6).")
    else:
        try:
            from transformers import AutoTokenizer
            from .. import config as C
            tok = AutoTokenizer.from_pretrained(C.ckpt("dpo")[0], revision=C.ckpt("dpo")[1])
            dec = lambda t: repr(tok.decode([t]))  # noqa: E731
        except Exception:                                       # noqa: BLE001 - laptop without transformers
            dec = lambda t: f"id {t}"  # noqa: E731
        for comp in "AD":
            rows = [r for r in kd.values() if r.get("trace_ckpt") == "rlvr" and r["component"] == comp
                    and r.get("status") == "valid" and r.get("kl_pos_bins")]
            bins = np.nanmean(np.array([[np.nan if x is None else x for x in r["kl_pos_bins"]] for r in rows]), axis=0)
            tot, cnt = collections.Counter(), collections.Counter()
            for r in rows:
                for t, s, c in r["kl_by_token_top"]:
                    tot[t] += s
                    cnt[t] += c
            allkl = sum(r["sum_kl_think"] for r in rows)
            L += [f"### {comp} (RLVR-written traces, n = {len(rows)})", "",
                  "Mean KL by relative position in the think block (bin 1 = start, 20 = end): " +
                  ", ".join(f"{x:.3f}" for x in bins), "",
                  "| rank | token | total KL | share of all think KL | count | mean KL per occurrence |", "|---|---|---|---|---|---|"]
            for j, (t, s) in enumerate(tot.most_common(30), 1):
                L.append(f"| {j} | {dec(t)} | {s:.1f} | {s / allkl:.3f} | {cnt[t]} | {s / cnt[t]:.3f} |")
            L += ["", "Token totals are summed over each trace's top 50 tokens by KL, so tails are undercounted.", ""]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
