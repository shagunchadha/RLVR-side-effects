"""B2 summary: indeterminacy vs self-reference (registration amendment 3 "B2").

    python -m exp.analysis.b2_summary            -> results/sprint/B2/summary.md

H: the RLVR - DPO increase in think length is driven by indeterminacy, not self-reference: the indeterminate cells
(self and other) increase more than the determinate ones, and the self x indeterminacy interaction is small.
Primary: per cell, the median over items of the paired think-length difference RLVR - DPO (per item, mean over
seeds); indeterminacy main effect = mean of the two indeterminate cell medians - mean of the two determinate ones;
interaction = (self-indet - self-det) - (other-indet - other-det); each with a bootstrap over items within cells
(10,000, seed 20261024, per-label generator). "Small" interaction (operational) = its 95% CI lies within +-25% of the
indeterminacy main effect. Think tokens and validity as in B3.
"""
import collections
import sys

import numpy as np

from . import sprint_common as C

CELLS = ("self_indet", "self_det", "other_indet", "other_det")
ARMS = {"rlvr": "rlvr__sys-own", "dpo": "dpo__sys-own", "sft": "sft__sys-own"}


def per_item(rows):
    acc, cell = collections.defaultdict(list), {}
    for r in rows:
        cell[r["id"]] = r["cell"]
        if r["status"] == "valid" and r["think_tokens"] is not None:
            acc[r["id"]].append(r["think_tokens"])
    return {u: float(np.mean(v)) for u, v in acc.items()}, cell


def stats(med):
    m = {c: med[..., i] for i, c in enumerate(CELLS)}
    main = (m["self_indet"] + m["other_indet"]) / 2 - (m["self_det"] + m["other_det"]) / 2
    inter = (m["self_indet"] - m["self_det"]) - (m["other_indet"] - m["other_det"])
    return main, inter


def main():
    shards = {p.parts[-3]: p for p in C.fetch("runs/B2/")}
    cols = ["id", "cell", "seed", "status", "think_tokens", "correct"]
    rows = {ck: C.read(shards[d], cols) for ck, d in ARMS.items()}
    M, cell = {}, {}
    for ck in ARMS:
        M[ck], c = per_item(rows[ck])
        cell.update(c)
    L = ["# B2: indeterminacy vs self-reference", "",
         "Generated by `exp/analysis/b2_summary.py` from the B2 shards on HF (`runs/B2/`). Registration: amendment 3 (B2). "
         "Cells: self-indeterminate = A wordings (48), self-determinate = yes/no facts about the model (40), "
         "other-indeterminate = third-person A wordings and opinion items (40), other-determinate = D items (40); "
         "10 seeds; own templates. CIs: bootstrap over items within cells (10,000, seed 20261024, per-label generator).", "",
         "**Registered H:** the RLVR − DPO think-length increase is driven by indeterminacy: the indeterminate cells "
         "increase more than the determinate ones, and the self × indeterminacy interaction is small (95% CI within ±25% "
         "of the main effect).", "", "## Per cell", "",
         "| cell | items | valid RLVR / DPO / SFT | mean think tokens RLVR / DPO / SFT | median RLVR − DPO [95% CI] | "
         "mean RLVR − DPO [95% CI] | median DPO − SFT (own template, confounded) |", "|---|---|---|---|---|---|---|"]
    D, cell_units, Dsft = {}, {}, {}
    for c in CELLS:
        us = sorted(u for u in set(M["rlvr"]) & set(M["dpo"]) if cell[u] == c)
        cell_units[c] = us
        D[c] = np.array([M["rlvr"][u] - M["dpo"][u] for u in us])
        Dsft[c] = np.array([M["dpo"][u] - M["sft"][u] for u in us if u in M["sft"]])
    idx = {c: C.DI.make_rng(f"B2|{c}").integers(0, len(D[c]), size=(10000, len(D[c]))) for c in CELLS}
    meds = np.stack([np.median(D[c][idx[c]], axis=1) for c in CELLS], axis=1)
    point = np.array([[np.median(D[c]) for c in CELLS]])
    for i, c in enumerate(CELLS):
        val = {ck: sum(1 for r in rows[ck] if r["cell"] == c and r["status"] == "valid") for ck in ARMS}
        n = {ck: sum(1 for r in rows[ck] if r["cell"] == c) for ck in ARMS}
        mt = {ck: np.mean([M[ck][u] for u in cell_units[c] if u in M[ck]]) for ck in ARMS}
        lo, hi = C.DI.percentile_ci(meds[:, i])
        mr = C.ci_mean(D[c], f"B2|mean|{c}")
        L.append(f"| {c} | {len(cell_units[c])} | {val['rlvr']}/{n['rlvr']}, {val['dpo']}/{n['dpo']}, {val['sft']}/{n['sft']} | "
                 f"{mt['rlvr']:.0f} / {mt['dpo']:.0f} / {mt['sft']:.0f} | {point[0, i]:+.1f} [{lo:+.1f}, {hi:+.1f}] | "
                 f"{mr[0]:+.1f} [{mr[1]:+.1f}, {mr[2]:+.1f}] | {np.median(Dsft[c]):+.1f} |")
    mb, ib = stats(meds)
    mp, ip = stats(point)
    mlo, mhi = C.DI.percentile_ci(mb)
    ilo, ihi = C.DI.percentile_ci(ib)
    main_v = "result" if mlo > 0 else ("opposite" if mhi < 0 else "no result (CI includes 0)")
    small = abs(ilo) <= 0.25 * abs(mp[0]) and abs(ihi) <= 0.25 * abs(mp[0])
    # ratio version: RLVR / DPO per cell (descriptive)
    L += ["", "## Primary contrasts (on the cell medians of RLVR − DPO, think tokens)", "",
          "| contrast | estimate [95% CI] | registered | verdict |", "|---|---|---|---|",
          f"| indeterminacy main effect | {mp[0]:+.1f} [{mlo:+.1f}, {mhi:+.1f}] | > 0 | {main_v} |",
          f"| self × indeterminacy interaction | {ip[0]:+.1f} [{ilo:+.1f}, {ihi:+.1f}] | small: within ±{0.25 * abs(mp[0]):.1f} "
          f"(25% of the main effect) | {'small (result)' if small else ('inconclusive: CI includes 0 but exceeds the bound' if ilo < 0 < ihi else 'not small')} |"]
    rel = {c: np.mean([M['rlvr'][u] for u in cell_units[c]]) / np.mean([M['dpo'][u] for u in cell_units[c]]) for c in CELLS}
    L += ["", "Ratio RLVR / DPO of mean think tokens per cell (descriptive): " +
          "; ".join(f"{c} {rel[c]:.2f}" for c in CELLS), "",
          "## Verdict", "",
          f"- **Indeterminate cells increase more than determinate ones: {main_v}** ({mp[0]:+.1f} tokens [{mlo:+.1f}, {mhi:+.1f}]).",
          f"- **Self × indeterminacy interaction small: {'yes' if small else 'no'}** ({ip[0]:+.1f} [{ilo:+.1f}, {ihi:+.1f}]; "
          f"bound ±{0.25 * abs(mp[0]):.1f}).",
          f"- **B2-H overall: {'supported' if main_v == 'result' and small else 'partly supported: the indeterminacy main effect holds; that the interaction is small is not established'}.**",
          "", "**Reading (not registered):** in absolute tokens, the RLVR − DPO increase is concentrated in the indeterminate "
          "cells, self and other alike (+608 and +810 median), against +114 and +53 in the determinate cells. The point "
          "estimate of the interaction is negative: if anything, *other*-indeterminate items lengthen more than self ones, "
          "so self-reference is not the driver. In relative terms, though, self-determinate items also roughly double "
          "(ratio 2.20) from a short base, while D items barely move (1.19).", ""]
    out = C.ROOT / "results" / "sprint" / "B2"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
