"""B8 summary: response style on IPIP-NEO-120 (registration amendment 3 "B8", amendments 6, 9).

    python -m exp.analysis.b8_summary            -> results/sprint/B8/summary.md

H (amendment 3): extreme-response style RLVR > DPO, and acquiescence RLVR < DPO. Primary indices, paired by item
(acquiescence: by facet with both keys, n = 21): extreme = share of valid answers in {1, 5}; midpoint = share of 3;
acquiescence = mean raw rating of positively keyed - reverse-keyed items per facet, averaged. Secondary: readout
P(1) + P(5), P(3); all-facet acquiescence = mean raw rating over all items. DPO - SFT(dpo_default) is reported next to it.
"""
import collections
import json
import sys

import numpy as np

from . import sprint_common as C

ARMS = {"rlvr": "rlvr__sys-own", "dpo": "dpo__sys-own", "sft": "sft__sys-dpo_default"}
COLS = ["id", "trait", "key", "seed", "status", "answer_strict", "think_tokens", "p_read_1", "p_read_3", "p_read_5",
        "read_primary"]


def per_item(rows):
    by = collections.defaultdict(list)
    for r in rows:
        by[r["id"]].append(r)
    out = collections.defaultdict(dict)
    for i, rs in by.items():
        v = [int(r["answer_strict"]) for r in rs if r["status"] == "valid" and r["answer_strict"] is not None]
        rd = [r for r in rs if r.get("read_primary") and r["p_read_1"] is not None]
        if v:
            out["extreme"][i] = float(np.mean([a in (1, 5) for a in v]))
            out["midpoint"][i] = float(np.mean([a == 3 for a in v]))
            out["rating"][i] = float(np.mean(v))
        if rd:
            out["read_extreme"][i] = float(np.mean([r["p_read_1"] + r["p_read_5"] for r in rd]))
            out["read_midpoint"][i] = float(np.mean([r["p_read_3"] for r in rd]))
        tt = [r["think_tokens"] for r in rs if r["status"] == "valid" and r["think_tokens"] is not None]
        if tt:
            out["think_tokens"][i] = float(np.mean(tt))
    return out


def acquiescence(rating, meta):
    """{facet: mean raw rating of + keyed items - mean raw rating of reverse-keyed items} for facets with both keys."""
    acc = collections.defaultdict(lambda: {1: [], -1: []})
    for i, v in rating.items():
        acc[meta[i]["facet"]][meta[i]["key"]].append(v)
    return {f: float(np.mean(k[1]) - np.mean(k[-1])) for f, k in acc.items() if k[1] and k[-1]}


def main():
    items = json.load(open(C.ROOT / "items_sprint" / "items_B8_ipipneo120.json", encoding="utf-8"))["items"]
    meta = {it["id"]: it for it in items}
    shards = {p.parts[-3]: p for p in C.fetch("runs/B8/")}
    rows = {ck: C.read(shards[d], COLS) for ck, d in ARMS.items()}
    M = {ck: per_item(r) for ck, r in rows.items()}
    acq = {ck: acquiescence(M[ck]["rating"], meta) for ck in ARMS}
    L = ["# B8: response style on IPIP-NEO-120", "",
         "Generated by `exp/analysis/b8_summary.py` from the B8 shards on HF (`runs/B8/`). Registration: amendment 3 (B8), "
         "amendments 6 and 9 (items sha256 `ca5bea59…`, check against ipip.ori.org). Statistics: mean of paired "
         "differences, percentile bootstrap over units (10,000, seed 20261024, per-label generator), two-sided Wilcoxon. "
         "A *result* is a 95% CI that excludes 0 in the registered direction.", "",
         "**Registered H:** extreme-response style RLVR > DPO, and acquiescence RLVR < DPO.", "",
         "## Arms", "", "| arm | generations | valid | extreme share | midpoint share | mean raw rating | "
         "readout P(1)+P(5) | readout P(3) | mean think tokens |", "|---|---|---|---|---|---|---|---|---|"]
    names = {"rlvr": "RLVR (own)", "dpo": "DPO (own)", "sft": "SFT (DPO system prompt)"}
    for ck in ARMS:
        m, r = M[ck], rows[ck]
        nv = sum(1 for x in r if x["status"] == "valid")
        L.append(f"| {names[ck]} | {len(r)} | {nv} | {np.mean(list(m['extreme'].values())):.3f} | "
                 f"{np.mean(list(m['midpoint'].values())):.3f} | {np.mean(list(m['rating'].values())):.2f} | "
                 f"{np.mean(list(m['read_extreme'].values())):.3f} | {np.mean(list(m['read_midpoint'].values())):.3f} | "
                 f"{np.mean(list(m['think_tokens'].values())):.0f} |")
    res = {}
    L += ["", "## Paired contrasts", "", "| index | unit | RLVR − DPO [95% CI] | registered | verdict | DPO − SFT(dpo_default) [95% CI] |",
          "|---|---|---|---|---|---|"]
    spec = [("extreme", "extreme share {1,5} (primary)", "item", +1),
            ("acq", "acquiescence, facets with both keys (primary)", "facet", -1),
            ("midpoint", "midpoint share (primary, no registered direction)", "item", 0),
            ("read_extreme", "readout P(1)+P(5) (secondary)", "item", +1),
            ("read_midpoint", "readout P(3) (secondary)", "item", 0),
            ("rating", "all-facet acquiescence = mean raw rating (secondary)", "item", -1),
            ("think_tokens", "think tokens (descriptive)", "item", 0)]
    for k, name, unit, direc in spec:
        a, b, c = (acq["rlvr"], acq["dpo"], acq["sft"]) if k == "acq" else (M["rlvr"][k], M["dpo"][k], M["sft"][k])
        r1 = C.paired(a, b, f"B8|rlvr-dpo|{k}")
        r2 = C.paired(b, c, f"B8|dpo-sft|{k}")
        res[k] = r1
        nd = 1 if k == "think_tokens" else 3
        reg = {1: "RLVR > DPO", -1: "RLVR < DPO", 0: "—"}[direc]
        v = C.verdict(r1, direc) if direc else "descriptive"
        L.append(f"| {name} | {unit} (n = {r1['n']}) | {C.fmt(r1, nd)} | {reg} | {v} | {C.fmt(r2, nd)} |")
    L += ["", "## Extreme share by domain (RLVR − DPO, descriptive)", "", "| domain | items | RLVR − DPO [95% CI] |", "|---|---|---|"]
    for dom in "NEOAC":
        ids = [i for i in M["rlvr"]["extreme"] if meta[i]["domain"] == dom]
        r = C.paired({i: M["rlvr"]["extreme"][i] for i in ids}, {i: M["dpo"]["extreme"][i] for i in ids if i in M["dpo"]["extreme"]},
                     f"B8|dom|{dom}")
        L.append(f"| {dom} | {r['n']} | {C.fmt(r)} |")
    ev, av = C.verdict(res["extreme"], +1), C.verdict(res["acq"], -1)
    L += ["", "## Verdict", "",
          f"- **B8-H (extreme RLVR > DPO): {ev}.** RLVR − DPO extreme share {C.fmt(res['extreme'])}. "
          f"Compare B1-H1 on the 48 A wordings: +0.181 [+0.131, +0.233].",
          f"- **B8-H (acquiescence RLVR < DPO): {av}.** RLVR − DPO {C.fmt(res['acq'])} over the facets with both keys.",
          "- **Context (descriptive, not registered):** SFT with the DPO system prompt is the most extreme arm, so DPO lowered "
          "extremity relative to SFT and RLVR moved part of the way back. RLVR also writes about twice DPO's think tokens "
          "here, as on A. The all-facet acquiescence index (mean raw rating) is lower for RLVR, but the registered, "
          "key-balanced index is not distinguishable from 0 at n = 21 facets.", ""]
    out = C.ROOT / "results" / "sprint" / "B8"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
