"""M4 summary: persona vectors (registration amendment 3 "M4", amendment 12).

    python -m exp.analysis.m4_summary            -> results/sprint/M4/summary.md

H (amendment 3): trait directions are stable across checkpoints (cos > 0.8), and RLVR shifts A-prompt projections on
at least one trait beyond the across-seed variation, even where the Likert mean is flat. Primary (amendment 12): per
trait, at layers 19 and 23 (and all layers), the projection difference RLVR - DPO onto DPO's unit directions, at the
prompt end and at think-64 (mean over the first 64 think tokens of valid B1 main-arm traces, seeds 0-9), per wording,
bootstrap over wordings (10,000, seed 20261024, per-label generator). "Beyond the across-seed variation": the mean over
wordings of the think-64 RLVR - DPO difference exceeds (in absolute value) the mean over wordings of the across-seed SD
of DPO's think-64 projection. Stability: cos(checkpoint direction, DPO direction) per trait and layer (shard metadata).
SFT sampling check (Oct 29): SFT's generation_config sets temperature 0.6 / top_p 0.95 (as DPO), and M4 passes
do_sample=True with those values; transformers' "flags not valid" warning refers to the stored config, not the call.
"""
import collections
import json
import sys

import numpy as np

from . import sprint_common as C

LAYERS = (4, 11, 15, 19, 23, 29)
PRIMARY = (19, 23)


def main():
    import pyarrow.parquet as pq
    data, cos = {}, {}
    for f in C.fetch("runs/M4/"):
        ck = f.parts[-3]
        data[ck] = C.read(f, ["id", "seed", "position", "trait", "layer", "proj_dpo"])
        md = pq.ParquetFile(f).schema_arrow.metadata
        cos[ck] = json.loads(md[b"cos_own_vs_dpo_direction"]) if b"cos_own_vs_dpo_direction" in md else {}
    traits = sorted({r["trait"] for r in data["dpo"]})
    P = {}
    for ck, rows in data.items():
        pe = collections.defaultdict(dict)
        th = collections.defaultdict(lambda: collections.defaultdict(list))
        for r in rows:
            k = (r["trait"], r["layer"])
            if r["position"] == "prompt_end":
                pe[k][r["id"]] = r["proj_dpo"]
            else:
                th[k][r["id"]].append(r["proj_dpo"])
        P[ck] = {"pe": pe, "th": {k: {u: float(np.mean(v)) for u, v in d.items()} for k, d in th.items()},
                 "sd": {k: {u: float(np.std(v, ddof=1)) for u, v in d.items() if len(v) > 1} for k, d in th.items()}}
    L = ["# M4: persona vectors", "",
         "Generated by `exp/analysis/m4_summary.py` from the M4 shards on HF (`runs/M4/`). Registration: amendment 3 (M4), "
         "amendment 12. Directions from 40 frozen Alpaca questions under contrastive system prompts (10 traits); "
         "projections onto DPO's unit directions for the 48 A wordings. CIs: percentile bootstrap over wordings "
         "(10,000, seed 20261024, per-label generator). 10 traits × 2 positions × 2 primary layers = 40 contrasts, no "
         "multiplicity correction (as registered).", "",
         "**Registered H:** (1) directions stable across checkpoints (cos > 0.8); (2) RLVR shifts A-prompt projections on "
         "at least one trait beyond the across-seed variation.", "",
         "## (1) Direction stability: cos(checkpoint direction, DPO direction)", "",
         "| checkpoint | trait | " + " | ".join(f"L{li}" for li in LAYERS) + " |", "|---|---|" + "---|" * len(LAYERS)]
    stab = {}
    for ck in ("rlvr", "sft"):
        for t in traits:
            v = cos.get(ck, {}).get(t)
            if v:
                L.append(f"| {ck.upper()} | {t} | " + " | ".join(f"{x:.3f}" for x in v) + " |")
                stab[(ck, t)] = v
    allp = [x for (ck, t), v in stab.items() for li, x in zip(LAYERS, v) if li in PRIMARY]
    n_ok = sum(x > 0.8 for x in allp)
    L += ["", f"At layers 19/23: {n_ok} of {len(allp)} (checkpoint, trait, layer) cosines exceed 0.8 "
          f"(min {min(allp):.3f}, median {np.median(allp):.3f}).", "",
          "## (2) Projection difference RLVR − DPO (onto DPO's unit directions)", "",
          "| trait | layer | prompt end [95% CI] | think-64 [95% CI] | mean across-seed SD of DPO (think-64) | beyond seed variation |",
          "|---|---|---|---|---|---|"]
    hits = []
    for t in traits:
        for li in PRIMARY:
            k = (t, li)
            rp = C.paired(P["rlvr"]["pe"][k], P["dpo"]["pe"][k], f"M4|pe|{t}|{li}")
            rt = C.paired(P["rlvr"]["th"][k], P["dpo"]["th"][k], f"M4|th|{t}|{li}")
            sd = float(np.mean(list(P["dpo"]["sd"][k].values())))
            beyond = abs(rt["mean"]) > sd
            ci_ok = rt["lo"] > 0 or rt["hi"] < 0
            if beyond and ci_ok:
                hits.append((t, li, rt["mean"], sd))
            L.append(f"| {t} | L{li} | {C.fmt(rp, 3)} | {C.fmt(rt, 3)} | {sd:.3f} | {'yes' if beyond else 'no'}{' (CI excludes 0)' if ci_ok else ''} |")
    L += ["", "All layers (think-64, RLVR − DPO, mean over wordings; * = CI excludes 0):", "",
          "| trait | " + " | ".join(f"L{li}" for li in LAYERS) + " |", "|---|" + "---|" * len(LAYERS)]
    for t in traits:
        cells = []
        for li in LAYERS:
            r = C.paired(P["rlvr"]["th"][(t, li)], P["dpo"]["th"][(t, li)], f"M4|all|{t}|{li}")
            cells.append(f"{r['mean']:+.3f}{'*' if (r['lo'] > 0 or r['hi'] < 0) else ''}")
        L.append(f"| {t} | " + " | ".join(cells) + " |")
    stable = n_ok == len(allp)
    L += ["", "## Verdict", "",
          f"- **(1) Directions stable (cos > 0.8): {'yes' if stable else ('failed' if n_ok <= len(allp) // 4 else 'partly')}** "
          f"({n_ok}/{len(allp)} at layers 19/23; median cos {np.median(allp):.2f}).",
          f"- **(2) RLVR shifts the projection on at least one trait beyond seed variation: {'result' if hits else 'no result'}.** "
          + ("; ".join(f"{t} L{li}: {m:+.3f} vs SD {s:.3f}" for t, li, m, s in hits) if hits else
             "No trait's think-64 difference exceeds DPO's across-seed SD with a CI excluding 0."),
          "", "**Reading (not registered):**",
          "- **Caution on (2):** because (1) fails (RLVR's own trait directions are only about cos 0.5 from DPO's), a "
          "shift along DPO's direction need not mean that RLVR represents *its* trait differently. Part of it can be a "
          "generic representational offset between the models.",
          "- The prompt-end CIs are very narrow because the prompt-end projection has no sampling noise: every wording "
          "shifts by nearly the same amount, which again points to a model-level offset more than to item-specific effects.",
          "- **Direction of the think-64 shifts:** RLVR sits *lower* than DPO on sycophantic, approval, confidence and "
          "composure, and *higher* on hedging and humility, from layer 19 on. That is the opposite of a "
          "\"more confident persona\" account of the extreme-answer shift. Together with M3, the extremity looks "
          "built during deliberation rather than carried by a persona shift present at the start of the think block.", ""]
    out = C.ROOT / "results" / "sprint" / "M4"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
