"""B3 summary: reasoning cap x answer format, on A and D (registration "B3"; B3a = RLVR and DPO, B3b = SFT).

    python -m exp.analysis.b3_summary            -> results/sprint/B3a/summary.md  (B3b's SFT arm is added when present)

Hypotheses (registration "B3"):
  B3-H1 the reasoning cap barely shortens thinking at any checkpoint: per item log(think tokens with cap / without cap)
        in the strict condition, mean per checkpoint; result = CI within +-log(1.25).
  B3-H2 RLVR's think-length excess on self-report over commonsense survives without instruction: (RLVR - DPO on A) -
        (RLVR - DPO on D) > 0 in the bare, no-cap cell; A and D bootstrapped independently.
  B3-H3 RLVR follows the one-sentence justification better than DPO: RLVR < DPO in justification sentences (strict,
        cap, A; per wording, paired).
  B3-H4 (exploratory) A extreme share strict - bare, per checkpoint. B3-H5 descriptive: format compliance, D accuracy.
Validity: strict cells need the think block closed and the frozen parser's answer (status valid); bare cells need the
think block closed and a lenient answer. Units: A wording (48), D item (50); mean over seeds. CIs: percentile bootstrap
over units (10,000, seed 20261024, per-label generator); two-sided Wilcoxon.
"""
import collections
import sys

import numpy as np

from . import sprint_common as C

COLS = ["id", "component", "cap", "fmt", "seed", "status", "closed", "answer_strict", "answer_lenient", "think_tokens",
        "post_sentences", "format_ok", "correct"]
CELLS = [(True, "strict"), (False, "strict"), (True, "bare"), (False, "bare")]


def valid(r):
    if not r["closed"]:
        return False
    return r["status"] == "valid" if r["fmt"] == "strict" else r["answer_lenient"] not in (None, "")


def unit(rows, comp, cap, fmt, fn, need_valid=True):
    acc = collections.defaultdict(list)
    for r in rows:
        if r["component"] == comp and bool(r["cap"]) == cap and r["fmt"] == fmt and (valid(r) or not need_valid):
            v = fn(r)
            if v is not None:
                acc[r["id"]].append(v)
    return {u: float(np.mean(v)) for u, v in acc.items()}


def answer(r):
    a = r["answer_strict"] if r["fmt"] == "strict" else r["answer_lenient"]
    return None if a in (None, "") else str(a)


def main():
    arms = {}
    for f in C.fetch("runs/B3/"):
        ck = f.parts[-3].split("__")[0]
        arms[ck] = C.read(f, COLS)
    cks = [c for c in ("rlvr", "dpo", "sft") if c in arms]
    L = ["# B3: reasoning cap × answer format, on A and D", "",
         "Generated by `exp/analysis/b3_summary.py` from the B3 shards on HF (`runs/B3/`). Arms present: "
         + ", ".join(c.upper() for c in cks) + " (B3a = RLVR and DPO; B3b = SFT, "
         + ("included" if "sft" in arms else "not run yet") + "). Registration: \"B3\". 48 A wordings + 50 D items "
         "(o0) × 4 cells × 10 seeds per checkpoint. CIs: percentile bootstrap over units (10,000, seed 20261024, "
         "per-label generator).", "", "## Cells", "",
         "| checkpoint | component | cap | format | generations | valid | mean think tokens | format ok (strict) | "
         "D accuracy (valid) |", "|---|---|---|---|---|---|---|---|---|"]
    for ck in cks:
        for comp in ("A", "D"):
            for cap, fmt in CELLS:
                rs = [r for r in arms[ck] if r["component"] == comp and bool(r["cap"]) == cap and r["fmt"] == fmt]
                v = [r for r in rs if valid(r)]
                fo = np.mean([bool(r["format_ok"]) for r in rs]) if fmt == "strict" else float("nan")
                acc = np.mean([bool(r["correct"]) for r in v]) if comp == "D" and v else float("nan")
                L.append(f"| {ck.upper()} | {comp} | {'cap' if cap else 'no cap'} | {fmt} | {len(rs)} | {len(v)} | "
                         f"{np.mean([r['think_tokens'] for r in v]) if v else float('nan'):.0f} | "
                         f"{'' if np.isnan(fo) else f'{fo:.3f}'} | {'' if np.isnan(acc) else f'{acc:.3f}'} |")
    L += ["", "## B3-H1: the cap barely shortens thinking (strict; |cap effect| < 20%)", "",
          "| checkpoint | component | mean log(cap / no cap) [95% CI] | as ratio | within ±log(1.25)? |", "|---|---|---|---|---|"]
    h1 = {}
    for ck in cks:
        for comp in ("A", "D"):
            a = unit(arms[ck], comp, True, "strict", lambda r: r["think_tokens"])
            b = unit(arms[ck], comp, False, "strict", lambda r: r["think_tokens"])
            d = {u: np.log(a[u] / b[u]) for u in set(a) & set(b) if a[u] > 0 and b[u] > 0}
            m, lo, hi = C.ci_mean(list(d.values()), f"B3|H1|{ck}|{comp}")
            ok = -np.log(1.25) < lo and hi < np.log(1.25)
            h1[(ck, comp)] = ok
            L.append(f"| {ck.upper()} | {comp} | {m:+.3f} [{lo:+.3f}, {hi:+.3f}] | {np.exp(m):.2f} | {'yes (result)' if ok else 'no'} |")
    L += ["", "## B3-H2: A-vs-D excess survives without instruction (bare, no cap)", ""]
    A_r, A_d = unit(arms["rlvr"], "A", False, "bare", lambda r: r["think_tokens"]), unit(arms["dpo"], "A", False, "bare", lambda r: r["think_tokens"])
    D_r, D_d = unit(arms["rlvr"], "D", False, "bare", lambda r: r["think_tokens"]), unit(arms["dpo"], "D", False, "bare", lambda r: r["think_tokens"])
    ua, ud = sorted(set(A_r) & set(A_d)), sorted(set(D_r) & set(D_d))
    da = np.array([A_r[u] - A_d[u] for u in ua])
    dd = np.array([D_r[u] - D_d[u] for u in ud])
    ra = C.DI.make_rng("B3|H2|A").integers(0, len(da), size=(10000, len(da)))
    rd = C.DI.make_rng("B3|H2|D").integers(0, len(dd), size=(10000, len(dd)))
    lo2, hi2 = C.DI.percentile_ci(da[ra].mean(1) - dd[rd].mean(1))
    est2 = float(da.mean() - dd.mean())
    v2 = "result" if lo2 > 0 else ("opposite" if hi2 < 0 else "no result (CI includes 0)")
    L += [f"- RLVR − DPO on A: {da.mean():+.1f} tokens (n = {len(da)}); on D: {dd.mean():+.1f} (n = {len(dd)}).",
          f"- **(A) − (D): {est2:+.1f} [{lo2:+.1f}, {hi2:+.1f}]** (registered > 0) → **{v2}**.", ""]
    # same contrast in each cell (descriptive)
    L += ["Same contrast in every cell (descriptive): " + "; ".join(
        f"{'cap' if cap else 'no cap'}/{fmt} "
        f"{np.mean([v for v in (lambda x, y: [x[u] - y[u] for u in set(x) & set(y)])(unit(arms['rlvr'], 'A', cap, fmt, lambda r: r['think_tokens']), unit(arms['dpo'], 'A', cap, fmt, lambda r: r['think_tokens']))]) - np.mean([v for v in (lambda x, y: [x[u] - y[u] for u in set(x) & set(y)])(unit(arms['rlvr'], 'D', cap, fmt, lambda r: r['think_tokens']), unit(arms['dpo'], 'D', cap, fmt, lambda r: r['think_tokens']))]):+.0f}"
        for cap, fmt in CELLS), ""]
    L += ["## B3-H3: one-sentence justification (strict, cap, A)", ""]
    js = {ck: unit(arms[ck], "A", True, "strict", lambda r: r["post_sentences"]) for ck in ("rlvr", "dpo")}
    r3 = C.paired(js["rlvr"], js["dpo"], "B3|H3")
    v3 = C.verdict(r3, -1)
    L += [f"- Mean justification sentences: RLVR {np.mean(list(js['rlvr'].values())):.2f}, DPO {np.mean(list(js['dpo'].values())):.2f}.",
          f"- **RLVR − DPO: {C.fmt(r3)}** (registered RLVR < DPO) → **{v3}**.", "",
          "## B3-H4 (exploratory): extreme share, strict − bare, per checkpoint (A)", "",
          "| checkpoint | cap | strict − bare [95% CI] | strict | bare |", "|---|---|---|---|---|"]
    ext = lambda r: (float(int(answer(r)) in (1, 5)) if answer(r) and answer(r).isdigit() else None)  # noqa: E731
    for ck in cks:
        for cap in (True, False):
            s = unit(arms[ck], "A", cap, "strict", ext)
            b = unit(arms[ck], "A", cap, "bare", ext)
            r4 = C.paired(s, b, f"B3|H4|{ck}|{cap}")
            L.append(f"| {ck.upper()} | {'cap' if cap else 'no cap'} | {C.fmt(r4)} | {np.mean(list(s.values())):.3f} | "
                     f"{np.mean(list(b.values())):.3f} |")
    L += ["", "RLVR − DPO extreme share per cell (A, paired by wording): " + "; ".join(
        f"{'cap' if cap else 'no cap'}/{fmt} {C.fmt(C.paired(unit(arms['rlvr'], 'A', cap, fmt, ext), unit(arms['dpo'], 'A', cap, fmt, ext), f'B3|ext|{cap}|{fmt}'))}"
        for cap, fmt in CELLS), ""]
    h1_line = "; ".join(f"{ck.upper()} {comp}: {'yes' if ok else 'no'}" for (ck, comp), ok in h1.items())
    L += ["## Verdict", "",
          f"- **B3-H1 (cap effect within ±20%, per checkpoint and component): {h1_line}.**"
          + ("" if "sft" in arms else " SFT pending (B3b)."),
          f"- **B3-H2 (A-vs-D excess survives bare, no cap): {v2}** ({est2:+.1f} [{lo2:+.1f}, {hi2:+.1f}]).",
          f"- **B3-H3 (RLVR fewer justification sentences): {v3}** ({C.fmt(r3)}).",
          "- B3-H4 and B3-H5: exploratory and descriptive, tables above.", ""]
    out = C.ROOT / "results" / "sprint" / "B3a"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
