"""B7 summary: self-report vs behaviour (registration amendment 9 "B7"; amendment 15 moved it to N2).

    python -m exp.analysis.b7_summary            -> results/sprint/B7/summary.md

Per checkpoint (RLVR own, DPO own, SFT with the DPO system prompt), descriptive (three checkpoints, no test):
  behaviour   hedge-word rate per 100 words (final answer; think block) on 100 TriviaQA questions x 5 seeds (B7 shards),
              and accuracy (normalised alias match); per item = mean over seeds, then mean over items.
  stated      B6 (iii) MMLU-Pro: accuracy, mean stated confidence, confidence - accuracy gap, ECE (10 equal-width bins),
              over valid generations (RLVR and DPO only: B6 has no SFT arm).
  self-report B1 main arms (model-default sampling, 48 wordings x 20 seeds): mean key-scored rating (reverse-keyed
              wordings scored 6 - a) of the hedging and the confidence wordings.
Pairs: self-reported hedging vs the hedge-word rate; self-reported confidence vs the stated-confidence - accuracy gap.
RLVR - DPO differences in the behavioural rates are given with paired bootstrap CIs over items (descriptive).
"""
import collections
import json
import sys

import numpy as np

from . import sprint_common as C

ARMS = {"rlvr": "rlvr__sys-own", "dpo": "dpo__sys-own", "sft": "sft__sys-dpo_default"}
B7_COLS = ["id", "seed", "closed", "hedge_final", "hedge_think", "correct", "n_tokens"]
CAL_COLS = ["id", "seed", "status", "confidence", "correct"]


def b1_main(arm):
    """Rows of the B1 main arm (no sampling override) for one arm directory, or None."""
    for f in C.fetch(f"runs/B1/{arm}/"):
        cfg = json.load(open(C.fetch(f"runs/B1/{arm}/{f.parts[-2]}/", "config.json")[0], encoding="utf-8"))
        if not cfg["sampling"].get("override"):
            return C.read(f, ["id", "trait", "key", "status", "answer_strict"])
    return None


def self_report(rows):
    out = {}
    for trait in ("hedging", "confidence"):
        by = collections.defaultdict(list)
        for r in rows:
            if r["trait"] == trait and r["status"] == "valid":
                a = int(r["answer_strict"])
                by[r["id"]].append(a if r["key"] == 1 else 6 - a)
        out[trait] = float(np.mean([np.mean(v) for v in by.values()])) if by else float("nan")
    return out


def ece(conf, corr, bins=10):
    conf, corr = np.asarray(conf) / 100.0, np.asarray(corr, float)
    idx = np.minimum((conf * bins).astype(int), bins - 1)
    return float(sum(np.abs(conf[idx == b].mean() - corr[idx == b].mean()) * (idx == b).mean()
                     for b in range(bins) if (idx == b).any()))


def main():
    beh = {}
    for ck, arm in ARMS.items():
        fs = C.fetch(f"runs/B7/{arm}/")
        if fs:
            beh[ck] = C.read(fs[0], B7_COLS)
    cal = {}
    for f in C.fetch("runs/B6/cal__"):
        cal[f.parts[-3].split("__")[1]] = C.read(f, CAL_COLS)
    sr = {ck: self_report(r) for ck, arm in ARMS.items() if (r := b1_main(arm))}

    def item_mean(rows, fn):
        by = collections.defaultdict(list)
        for r in rows:
            v = fn(r)
            if v is not None:
                by[r["id"]].append(v)
        return {u: float(np.mean(v)) for u, v in by.items()}

    L = ["# B7: self-report vs behaviour", "",
         "Generated by `exp/analysis/b7_summary.py`. Registration: amendment 9 \"B7\" (descriptive; three checkpoints, "
         "no test). Behaviour: B7 shards (100 TriviaQA questions × 5 seeds, \"Answer briefly.\" + the reasoning cap). "
         "Stated confidence: B6 (iii) MMLU-Pro shards. Self-report: B1 main arms. B8 facet scores are not used.", "",
         "## Behaviour: hedging on open factual questions", "",
         "| checkpoint | generations | think closed | hedges / 100 words, final answer | hedges / 100 words, think | "
         "accuracy |", "|---|---|---|---|---|---|"]
    hf, ht = {}, {}
    for ck in ARMS:
        if ck not in beh:
            L.append(f"| {ck.upper()} | pending | | | | |")
            continue
        rs = beh[ck]
        hf[ck] = item_mean(rs, lambda r: r["hedge_final"] if r["closed"] else None)
        ht[ck] = item_mean(rs, lambda r: r["hedge_think"] if r["closed"] else None)
        acc = item_mean(rs, lambda r: float(bool(r["correct"])))
        L.append(f"| {ck.upper()} | {len(rs)} | {np.mean([bool(r['closed']) for r in rs]):.3f} | "
                 f"{np.mean(list(hf[ck].values())):.3f} | {np.mean(list(ht[ck].values())):.3f} | "
                 f"{np.mean(list(acc.values())):.3f} |")
    if {"rlvr", "dpo"} <= set(hf):
        L += ["", f"- RLVR − DPO, hedges in the final answer (paired by item, descriptive): "
                  f"{C.fmt(C.paired(hf['rlvr'], hf['dpo'], 'B7|hedge_final'))}.",
              f"- RLVR − DPO, hedges in the think block: {C.fmt(C.paired(ht['rlvr'], ht['dpo'], 'B7|hedge_think'))}."]
    L += ["", "## Stated confidence: B6 (iii) MMLU-Pro", "",
          "| checkpoint | generations | valid | accuracy (valid) | mean stated confidence | confidence − accuracy | ECE |",
          "|---|---|---|---|---|---|---|"]
    gap = {}
    for ck in ("rlvr", "dpo"):
        if ck not in cal:
            L.append(f"| {ck.upper()} | pending (B6 (iii) still running) | | | | | |")
            continue
        v = [r for r in cal[ck] if r["status"] == "valid" and r["confidence"] is not None]
        conf = [r["confidence"] for r in v]
        corr = [bool(r["correct"]) for r in v]
        gap[ck] = np.mean(conf) / 100 - np.mean(corr)
        L.append(f"| {ck.upper()} | {len(cal[ck])} | {len(v)} | {np.mean(corr):.3f} | {np.mean(conf):.1f} | "
                 f"{gap[ck]:+.3f} | {ece(conf, corr):.3f} |")
    L += ["", "B6 (iii)'s registered test (RLVR higher ECE and gap) is reported in `results/sprint/B6/summary.md`.", "",
          "## Self-report (B1 main arms, key-scored mean rating, 1–5)", "",
          "| checkpoint | hedging wordings | confidence (overclaiming) wordings |", "|---|---|---|"]
    for ck in ARMS:
        s = sr.get(ck)
        L.append(f"| {ck.upper()} | {s['hedging']:.2f} | {s['confidence']:.2f} |" if s else f"| {ck.upper()} | pending | |")
    L += ["", "## Pairs (descriptive)", "",
          "| checkpoint | self-reported hedging | hedges / 100 words (final) | self-reported overconfidence | "
          "stated confidence − accuracy |", "|---|---|---|---|---|"]
    for ck in ARMS:
        s = sr.get(ck, {"hedging": float("nan"), "confidence": float("nan")})
        h = np.mean(list(hf[ck].values())) if ck in hf else float("nan")
        g = f"{gap[ck]:+.3f}" if ck in gap else ("n/a (no SFT arm in B6)" if ck == "sft" else "pending")
        L.append(f"| {ck.upper()} | {s['hedging']:.2f} | {h:.3f} | {s['confidence']:.2f} | {g} |")
    L += ["", "With three checkpoints these pairs are descriptive: they show whether the ordering of the self-reports "
          "matches the ordering of the behaviour, not a test of it.", ""]
    out = C.ROOT / "results" / "sprint" / "B7"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
