"""M5 summary: causal tests (registration amendment 3 "M5", amendments 5, 7). Exploratory interventions.

    python -m exp.analysis.m5_summary            -> results/sprint/M5/summary.md

Registered (amendment 3): +alpha x offset on DPO lengthens A traces in proportion to alpha and much more than D;
-offset on RLVR shortens A; ablating the backtracking direction in RLVR shortens A while changing the answer in < 10% of
items. Primary: the A/D think-length ratio at alpha = 1 relative to the model's baseline; the answer-change rate under
ablation vs RLVR baseline seed 0, judged against the seed-to-seed rate (baseline seed 1). Added (amendment 5): P(extreme)
from the B1 readout on the generated think text, and the sampled-answer extreme share. Units: EVAL items (24 A
wordings, 25 D items), one seed per condition; contrasts per condition vs the model's baseline, paired by item, with a
percentile bootstrap over items (10,000, seed 20261024, per-label generator).

Answer parsing: the M5 job decoded generations with the end-of-text token kept (`skip_special_tokens=False`), so the
frozen strict parser saw "ANSWER: 3<|endoftext|>" and returned no_answer for almost every row. Here the stored text is
re-parsed with that trailing token removed and hit_eos set from it, as in B1 (vLLM text has no EOS token); the parser
is unchanged. Think length and the readout were computed from the think block and are not affected. Disclosed in
docs/sprint/disclosure-ledger.md.
"""
import collections
import sys

import numpy as np

from . import sprint_common as C
from .. import config as CF
from .. import parsers as P

EOT = "<|endoftext|>"
CAP = 3000


def reparse(r, kinds):
    t = r["text"]
    eos = t.endswith(EOT)
    t = t[: -len(EOT)] if eos else t
    a = P.strict_answer(t, kinds[r["id"]], r["n_new"], CAP, eos)
    return a["status"], (None if a["answer"] is None else str(a["answer"]))


def ratio_ci(cond, base, a_ids, d_ids, label):
    """(mean A_cond / mean A_base) / (mean D_cond / mean D_base), bootstrap over A and D items independently."""
    ai = [u for u in a_ids if u in cond and u in base]
    di = [u for u in d_ids if u in cond and u in base]
    Ac, Ab = np.array([cond[u] for u in ai]), np.array([base[u] for u in ai])
    Dc, Db = np.array([cond[u] for u in di]), np.array([base[u] for u in di])
    est = (Ac.mean() / Ab.mean()) / (Dc.mean() / Db.mean())
    ra = C.DI.make_rng(label + "|A").integers(0, len(ai), size=(10000, len(ai)))
    rd = C.DI.make_rng(label + "|D").integers(0, len(di), size=(10000, len(di)))
    bs = (Ac[ra].mean(1) / Ab[ra].mean(1)) / (Dc[rd].mean(1) / Db[rd].mean(1))
    lo, hi = C.DI.percentile_ci(bs)
    return float(est), lo, hi, float(Ac.mean() / Ab.mean()), float(Dc.mean() / Db.mean())


def main():
    f = C.fetch("runs/M5/")[0]
    rows = C.read(f, ["condition", "model", "alpha", "layer", "id", "component", "seed", "think_tok", "closed", "n_new",
                      "status", "answer", "text", "read_ext"])
    kinds = {it["id"]: it["parser_kind"] for comp in "AD" for it in CF.load_items(comp)}
    for r in rows:
        r["status_reparsed"], r["answer_reparsed"] = reparse(r, kinds)
        r.pop("text")
    by = collections.defaultdict(dict)
    for r in rows:
        by[r["condition"]][r["id"]] = r
    a_ids = sorted({r["id"] for r in rows if r["component"] == "A"})
    d_ids = sorted({r["id"] for r in rows if r["component"] == "D"})
    conds = list(dict.fromkeys(r["condition"] for r in rows))
    get = lambda c, k, ids, f=float: {u: f(by[c][u][k]) for u in ids if u in by[c] and by[c][u][k] is not None}  # noqa: E731
    ext = lambda c: {u: float(int(by[c][u]["answer_reparsed"]) in (1, 5)) for u in a_ids  # noqa: E731
                     if u in by[c] and by[c][u]["status_reparsed"] == "valid" and by[c][u]["answer_reparsed"]}
    import pyarrow.parquet as pq
    md = pq.ParquetFile(f).schema_arrow.metadata
    L = ["# M5: causal tests (exploratory interventions)", "",
         "Generated by `exp/analysis/m5_summary.py` from the M5 shard on HF (`runs/M5/dpo_rlvr/`). Registration: "
         "amendment 3 (M5), amendment 5 (extremity outcomes), amendment 7 (split, layer 19, conditions). EVAL units: "
         f"{len(a_ids)} A wordings, {len(d_ids)} D items, one seed per condition, cap 3,000 new tokens. CIs: percentile "
         "bootstrap over items (10,000, seed 20261024, per-label generator).", "",
         f"Backtracking direction: held-out AUC {float(md[b'backtrack_auc_eval']):.3f} on {int(md[b'n_target_eval'])} EVAL "
         f"target positions; cos(offset, backtracking direction) at layer 19 = {float(md[b'cos_offset_backtrack']):.3f}.", "",
         "**Parsing note:** answers are re-parsed from the stored text (see the module docstring and the disclosure "
         "ledger); the job's own `status` column is not used.", "",
         "## Per condition", "", "| condition | A think tokens | D think tokens | A unclosed (cap) | A valid | D valid | "
         "A readout P(1)+P(5) | A sampled extreme share | D accuracy |", "|---|---|---|---|---|---|---|---|---|"]
    gold = {it["id"]: it.get("gold") or it.get("key") for it in CF.load_items("D")}
    for c in conds:
        A = [by[c][u] for u in a_ids if u in by[c]]
        Dd = [by[c][u] for u in d_ids if u in by[c]]
        e = ext(c)
        acc = [str(r["answer_reparsed"]) == str(gold.get(r["id"])) for r in Dd if r["status_reparsed"] == "valid"]
        L.append(f"| {c} | {np.mean([r['think_tok'] for r in A]):.0f} | {np.mean([r['think_tok'] for r in Dd]):.0f} | "
                 f"{sum(not r['closed'] for r in A)} | {sum(r['status_reparsed'] == 'valid' for r in A)}/{len(A)} | "
                 f"{sum(r['status_reparsed'] == 'valid' for r in Dd)}/{len(Dd)} | "
                 f"{np.nanmean([r['read_ext'] if r['read_ext'] is not None else np.nan for r in A]):.3f} | "
                 f"{np.mean(list(e.values())) if e else float('nan'):.3f} | {np.mean(acc) if acc else float('nan'):.3f} |")
    L += ["", "## Contrasts vs the model's baseline (paired by item)", "",
          "| condition | Δ A think tokens | Δ D think tokens | Δ A readout P(1)+P(5) | Δ A sampled extreme |",
          "|---|---|---|---|---|"]
    R = {}
    for c in conds:
        base = "dpo_base_s0" if c.startswith("dpo") else "rlvr_base_s0"
        if c == base:
            continue
        ra = C.paired(get(c, "think_tok", a_ids), get(base, "think_tok", a_ids), f"M5|{c}|lenA")
        rd = C.paired(get(c, "think_tok", d_ids), get(base, "think_tok", d_ids), f"M5|{c}|lenD")
        rx = C.paired(get(c, "read_ext", a_ids), get(base, "read_ext", a_ids), f"M5|{c}|rext")
        rs = C.paired(ext(c), ext(base), f"M5|{c}|sext")
        R[c] = (ra, rd, rx, rs)
        L.append(f"| {c} | {C.fmt(ra, 0)} | {C.fmt(rd, 0)} | {C.fmt(rx)} | {C.fmt(rs)} |")
    L += ["", "## Primary: A/D think-length ratio relative to baseline (alpha = 1)", "",
          "| condition | (A_cond/A_base) / (D_cond/D_base) [95% CI] | A_cond/A_base | D_cond/D_base | registered | verdict |",
          "|---|---|---|---|---|---|"]
    prim = {}
    for c, base, direc, reg in [("dpo_plus_offset_1.0", "dpo_base_s0", +1, "> 1 (A lengthens more than D)"),
                                ("rlvr_minus_offset_1.0", "rlvr_base_s0", -1, "< 1 (A shortens more than D)")]:
        est, lo, hi, ra_, rd_ = ratio_ci(get(c, "think_tok", a_ids + d_ids), get(base, "think_tok", a_ids + d_ids), a_ids, d_ids, f"M5|ratio|{c}")
        v = ("result" if lo > 1 else "opposite" if hi < 1 else "no result (CI includes 1)") if direc > 0 else \
            ("result" if hi < 1 else "opposite" if lo > 1 else "no result (CI includes 1)")
        prim[c] = (est, lo, hi, v)
        L.append(f"| {c} | {est:.3f} [{lo:.3f}, {hi:.3f}] | {ra_:.3f} | {rd_:.3f} | {reg} | {v} |")
    L += ["", "Dose (A think tokens vs alpha): " + "; ".join(
        f"{m.upper()} " + ", ".join(f"α={a}: {np.mean([by[f'{m}_{s}_offset_{a}'][u]['think_tok'] for u in a_ids]):.0f}"
                                    for a in ("0.5", "1.0", "2.0"))
        for m, s in (("dpo", "plus"), ("rlvr", "minus"))) +
        f" (baselines: DPO {np.mean([by['dpo_base_s0'][u]['think_tok'] for u in a_ids]):.0f}, "
        f"RLVR {np.mean([by['rlvr_base_s0'][u]['think_tok'] for u in a_ids]):.0f}).", ""]

    def change(c, ref):
        ids = [u for u in a_ids + d_ids if u in by[c] and u in by[ref] and by[c][u]["answer_reparsed"] and by[ref][u]["answer_reparsed"]]
        ch = [by[c][u]["answer_reparsed"] != by[ref][u]["answer_reparsed"] for u in ids]
        lo, hi = __import__("exp.analysis.b1_summary", fromlist=["wilson"]).wilson(sum(ch), len(ch))
        return sum(ch), len(ch), lo, hi
    k1, n1, l1, h1 = change("rlvr_ablate_backtrack", "rlvr_base_s0")
    k0, n0, l0, h0 = change("rlvr_base_s1", "rlvr_base_s0")
    abl = R["rlvr_ablate_backtrack"]
    L += ["## Primary: backtracking ablation in RLVR", "",
          f"- Answer change vs RLVR baseline seed 0: ablation {k1}/{n1} = {k1 / max(n1, 1):.3f} [Wilson {l1:.3f}, {h1:.3f}]; "
          f"seed-to-seed (baseline seed 1) {k0}/{n0} = {k0 / max(n0, 1):.3f} [{l0:.3f}, {h0:.3f}]. Registered: < 10%.",
          f"- Δ A think tokens: {C.fmt(abl[0], 0)} (registered: shorter); Δ D think tokens {C.fmt(abl[1], 0)}.",
          f"- Δ A readout P(1)+P(5): {C.fmt(abl[2])}; Δ sampled extreme share: {C.fmt(abl[3])}.", ""]
    abl_len_v = C.verdict(abl[0], -1)
    L += ["## Verdict", "",
          f"- **+offset on DPO lengthens A more than D (A/D ratio at α = 1 > 1): {prim['dpo_plus_offset_1.0'][3]}** "
          f"({prim['dpo_plus_offset_1.0'][0]:.3f} [{prim['dpo_plus_offset_1.0'][1]:.3f}, {prim['dpo_plus_offset_1.0'][2]:.3f}]).",
          f"- **−offset on RLVR shortens A (more than D): {prim['rlvr_minus_offset_1.0'][3]}** "
          f"({prim['rlvr_minus_offset_1.0'][0]:.3f} [{prim['rlvr_minus_offset_1.0'][1]:.3f}, {prim['rlvr_minus_offset_1.0'][2]:.3f}]); "
          f"Δ A think tokens {C.fmt(R['rlvr_minus_offset_1.0'][0], 0)}.",
          f"- **Ablating the backtracking direction shortens A: {abl_len_v}** ({C.fmt(abl[0], 0)}); answer change "
          f"{k1 / max(n1, 1):.3f} vs seed-to-seed {k0 / max(n0, 1):.3f} (registered < 10%).",
          f"- **Extremity under the interventions (amendment 5):** ablation Δ readout P(extreme) {C.fmt(abl[2])}; "
          f"+offset (α = 1) on DPO {C.fmt(R['dpo_plus_offset_1.0'][2])}; −offset (α = 1) on RLVR {C.fmt(R['rlvr_minus_offset_1.0'][2])}.",
          f"- **Answer change under ablation < 10%: failed as registered** ({k1 / max(n1, 1):.3f}), but the seed-to-seed "
          f"rate is itself {k0 / max(n0, 1):.3f}. The ablation changes answers no more than resampling does.",
          "", "**Reading (not registered):**",
          "- **Ablating backtracking removes more than half of RLVR's A deliberation** (1175 → 506 tokens, about DPO's "
          "523) without moving the answer beyond seed noise. **But it does not reduce extremity:** P(extreme) stays at "
          "or above baseline (+0.13, CI includes 0). At this resolution, the extra deliberation that ablation removes is "
          "not what produces the extreme answers.",
          "- **The stage offset is not a clean length knob.** On DPO, +offset lengthens A with dose (523 → 598 → 715 → "
          "1028) and also lengthens D (A/D ratio CI includes 1). On RLVR, −offset does not shorten A at α ≤ 1. Every "
          "offset condition, in both directions and on both models, *raises* P(extreme). That pattern fits a generic "
          "off-distribution effect on the readout better than a specific deliberation → extremity pathway.",
          "- **Patching RLVR's prompt-position residuals into DPO** at early and middle layers (4, 11, 15) lengthens A "
          "(+290 to +350) but not D. P(extreme) rises at layers 15 and 19, so part of RLVR's A-specific state is set "
          "at the prompt, before any deliberation.",
          "", "All M5 contrasts rest on one seed per condition and 24 + 25 items; they are exploratory (amendment 7).", ""]
    out = C.ROOT / "results" / "sprint" / "M5"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
