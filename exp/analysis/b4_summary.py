"""B4 summary: reward domain (RL-Zero) (registration amendment 3 "B4", amendments 5, 10, 14).

    python -m exp.analysis.b4_summary            -> results/sprint/B4/summary.md

H (amendment 3): lengthening and the extreme-answer shift on self-report appear most in RL-Zero General/Mix (LM-judge
reward) and least in Math/Code. Mix is cut (amendment 14). Primary per domain (amendment 10), bootstrap over items:
(A length / D length) / base (A length / D length), ratio of per-item means; P(extreme) on A. Parse rates per model
and set. Length = `length_tok` as recorded by the job (amendment 10). Finished shards are used where they exist; a
domain still running (General) is read from its HF progress file and reported on the sets it has reached.
"""
import collections
import csv
import json
import sys

import numpy as np

from . import sprint_common as C

DOMAINS = ("base", "rl_zero_math", "rl_zero_code", "rl_zero_if", "rl_zero_general")
COLS = ["id", "set", "kind", "seed", "answer", "parse_rule", "has_think", "length_tok", "n_tokens", "finish_reason"]


def load():
    out, src = {}, {}
    for f in C.fetch("runs/B4/"):
        out[f.parts[-3]] = C.read(f, COLS)
        src[f.parts[-3]] = "shard"
    for p in C.fetch("progress/B4/", ".csv"):
        ck = p.parent.name.split("__")[0]
        if ck in out:
            continue
        csv.field_size_limit(2 ** 31 - 1)
        rows = []
        for r in csv.DictReader(open(p, encoding="utf-8")):
            try:
                d = json.loads(r["row_json"])
            except ValueError:
                continue
            rows.append({k: d.get(k) for k in COLS})
        out[ck], src[ck] = rows, f"progress ({len(rows)} of 1140 rows)"
    return out, src


def per_item(rows, s, fn):
    acc = collections.defaultdict(list)
    for r in rows:
        if r["set"] == s:
            v = fn(r)
            if v is not None:
                acc[r["id"]].append(v)
    return {u: float(np.mean(v)) for u, v in acc.items()}


def length(r):
    return float(r["length_tok"]) if r["length_tok"] is not None else None


def extreme(r):
    return float(int(r["answer"]) in (1, 5)) if r["answer"] not in (None, "") and str(r["answer"]).isdigit() else None


def ratio_boot(dA, dD, bA, bD, label):
    """(mean dA / mean dD) / (mean bA / mean bD); A and D items resampled independently (same draws for both models)."""
    ua, ud = sorted(set(dA) & set(bA)), sorted(set(dD) & set(bD))
    xa, xd = np.array([dA[u] for u in ua]), np.array([dD[u] for u in ud])
    ya, yd = np.array([bA[u] for u in ua]), np.array([bD[u] for u in ud])
    est = (xa.mean() / xd.mean()) / (ya.mean() / yd.mean())
    ra = C.DI.make_rng(label + "|A").integers(0, len(ua), size=(10000, len(ua)))
    rd = C.DI.make_rng(label + "|D").integers(0, len(ud), size=(10000, len(ud)))
    bs = (xa[ra].mean(1) / xd[rd].mean(1)) / (ya[ra].mean(1) / yd[rd].mean(1))
    lo, hi = C.DI.percentile_ci(bs)
    return float(est), lo, hi


def main():
    R, src = load()
    doms = [d for d in DOMAINS if d in R]
    L = ["# B4: reward domain (RL-Zero)", "",
         "Generated by `exp/analysis/b4_summary.py` from HF (`runs/B4/`, and `progress/B4/` for a domain still running). "
         "Registration: amendment 3 (B4), amendments 5, 10; Mix cut by amendment 14. Items: 48 A wordings, B2 "
         "self-determinate (40) and other-indeterminate (40), first 100 D base items (o0); 5 seeds. CIs: percentile "
         "bootstrap over items (10,000, seed 20261024, per-label generator).", "",
         "**Registered H:** lengthening and the extreme shift on self-report appear most in General/Mix and least in "
         "Math/Code.", "", "## Per model", "",
         "| model | source | sets reached | A parse rate | D parse rate | has think | A length | D length | "
         "A hit cap | A P(extreme) |", "|---|---|---|---|---|---|---|---|---|---|"]
    M = {}
    for d in doms:
        rows = R[d]
        sets = sorted({r["set"] for r in rows})
        pr = lambda s: np.mean([r["answer"] not in (None, "") for r in rows if r["set"] == s]) if any(r["set"] == s for r in rows) else float("nan")  # noqa: E731
        M[d] = {"lenA": per_item(rows, "A", length), "lenD": per_item(rows, "D", length), "ext": per_item(rows, "A", extreme)}
        capA = sum(1 for r in rows if r["set"] == "A" and r["finish_reason"] == "length")
        nA = sum(1 for r in rows if r["set"] == "A")
        L.append(f"| {d} | {src[d]} | {', '.join(sets)} | {pr('A'):.3f} | {pr('D'):.3f} | "
                 f"{np.mean([bool(r['has_think']) for r in rows]):.3f} | "
                 f"{np.mean(list(M[d]['lenA'].values())):.0f} | "
                 f"{(np.mean(list(M[d]['lenD'].values())) if M[d]['lenD'] else float('nan')):.0f} | {capA}/{nA} | "
                 f"{np.mean(list(M[d]['ext'].values())):.3f} |")
    L += ["", "## Primary: length ratio (A/D) relative to base, and P(extreme) on A", "",
          "| domain | (A/D) ÷ base (A/D) [95% CI] | A P(extreme) [95% CI] | P(extreme) − base, paired by wording [95% CI] |",
          "|---|---|---|---|"]
    res = {}
    for d in doms:
        if d == "base":
            continue
        if M[d]["lenD"]:
            est, lo, hi = ratio_boot(M[d]["lenA"], M[d]["lenD"], M["base"]["lenA"], M["base"]["lenD"], f"B4|ratio|{d}")
            rt = f"{est:.2f} [{lo:.2f}, {hi:.2f}]"
        else:
            est = lo = hi = float("nan")
            rt = "D not reached yet"
        e = C.ci_mean(list(M[d]["ext"].values()), f"B4|ext|{d}")
        pe = C.paired(M[d]["ext"], M["base"]["ext"], f"B4|ext-base|{d}")
        res[d] = {"ratio": (est, lo, hi), "ext": e, "ext_base": pe}
        L.append(f"| {d} | {rt} | {e[0]:.3f} [{e[1]:.3f}, {e[2]:.3f}] | {C.fmt(pe)} |")
    be = C.ci_mean(list(M["base"]["ext"].values()), "B4|ext|base")
    L.append(f"| base (3-shot, reference) | 1 | {be[0]:.3f} [{be[1]:.3f}, {be[2]:.3f}] | — |")
    L += ["", "## Domain contrasts (registered ordering: General > Math/Code)", "", "| contrast | estimate [95% CI] |", "|---|---|"]
    gen = "rl_zero_general"
    for a in ("rl_zero_math", "rl_zero_code"):
        if gen in M and a in M:
            L.append(f"| A P(extreme): General − {a.split('_')[-1].title()}, paired by wording | "
                     f"{C.fmt(C.paired(M[gen]['ext'], M[a]['ext'], f'B4|gen-{a}|ext'))} |")
            L.append(f"| A length: General − {a.split('_')[-1].title()}, paired by wording | "
                     f"{C.fmt(C.paired(M[gen]['lenA'], M[a]['lenA'], f'B4|gen-{a}|len'), 0)} |")
    L += ["", "## Verdict", ""]
    if gen in res and np.isnan(res[gen]["ratio"][0]):
        L.append(f"- **B4-H: not yet testable on length.** General has reached only {', '.join(sorted({r['set'] for r in R[gen]}))} "
                 f"({src[gen]}), so its A/D ratio is not available; Mix is cut. The extreme-shift half is reported on A below.")
    ordered = sorted((d for d in res if not np.isnan(res[d]["ratio"][0])), key=lambda d: -res[d]["ratio"][0])
    L.append("- Length ratio order: " + " > ".join(f"{d.split('_')[-1].title()} {res[d]['ratio'][0]:.2f}" for d in ordered) + ".")
    L.append("- A P(extreme) order: " + " > ".join(f"{d.split('_')[-1].title()} {res[d]['ext'][0]:.3f}"
                                                   for d in sorted(res, key=lambda d: -res[d]["ext"][0])) + f" (base {be[0]:.3f}).")
    L += [f"- **Extreme-shift half of B4-H: opposite.** General has the *lowest* A P(extreme), "
          f"below Math, Code and base; Code is by far the highest.",
          "", "**Data-quality caveats (they limit the length half):**",
          "- **IF** answers almost at once (mean length about 7 tokens on A and about 0 on D), so its A/D ratio is a "
          "ratio of near-zeros and is not interpretable.",
          "- **Math** rarely follows the multiple-choice format on D (parse rate 0.02), and 98 of its 240 A generations "
          "hit the 16K cap, so its lengths are dominated by runaway generations.",
          f"- **General** hits the cap on 71 of 240 A generations. Its A/D ratio, {res[gen]['ratio'][0]:.2f} "
          f"[{res[gen]['ratio'][1]:.2f}, {res[gen]['ratio'][2]:.2f}], is the lowest of the four domains, below Code's "
          f"{res['rl_zero_code']['ratio'][0]:.2f}, the only other domain whose lengths are interpretable (no test of the "
          "difference was registered; descriptive).",
          "- **Length half of B4-H: not supported.** General lengthens least relative to base, not most; with IF and "
          "Math degenerate, this rests on the General vs Code comparison alone.",
          "- With Mix cut and these caveats, B4 cannot cleanly separate LM-judge from verifiable reward on length. The "
          "extremity result is the more usable half, and it does not support the registered ordering.",
          "", "Note: RL-Zero models have no think block (`has_think` ≈ 0), so length is the tokens before the parsed answer "
          "line (amendment 10); it is not directly comparable with the Think checkpoints' think tokens.", ""]
    out = C.ROOT / "results" / "sprint" / "B4"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
