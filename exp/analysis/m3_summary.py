"""M3 summary: when is the Likert answer settled, and does extremity build up during the extra deliberation?
(registration amendment 3 "M3", amendment 5 "Added outputs").

    python -m exp.analysis.m3_summary            -> results/sprint/M3/summary.md

Registered (amendment 3): RLVR settles its final answer at a similar or earlier point than DPO, so most (> 50%) of
RLVR's extra tokens come after the settle point. Primary: share of the trace after the settle point, RLVR - DPO; probe
accuracy at prompt end per checkpoint. Amendment 5: (a') per-sentence P(extreme) = P(1) + P(5) and E[rating]
trajectories in 10 bins of relative position, RLVR vs DPO (and SFT), paired by wording; D analogue P(max letter) and
P(final letter); (a'') wrap-up onset = first sentence start with P(wrap-up) >= 0.2 (with and without "So"); primary
added test: per trace mean P(extreme) after the onset minus before it, RLVR vs DPO, paired by wording; registered
direction: extremity grows after the onset more for RLVR. Traces with no onset are counted, not imputed.
Alignment: p_sent[i] is the readout after sentence end i; p_wrapup_sent[i] is P(the next sentence starts with a
wrap-up word) at that point. "Before" = readouts at sentence ends 0..i_on; "after" = i_on + 1 .. end.
"""
import collections
import json
import sys

import numpy as np

from . import sprint_common as C

CKS = ("rlvr", "dpo", "sft")
NB = 10


def load():
    out = {}
    for f in C.fetch("runs/M3/"):
        import pyarrow.parquet as pq
        out[f.parts[-3]] = {"rows": C.read(f), "probes": json.loads(pq.ParquetFile(f).schema_arrow.metadata.get(b"probes", b"{}"))}
    return out


def by_unit(rows, fn):
    acc = collections.defaultdict(list)
    for r in rows:
        v = fn(r)
        if v is not None and not (isinstance(v, float) and np.isnan(v)):
            acc[r["id"]].append(v)
    return {u: float(np.mean(v)) for u, v in acc.items() if v}


def ext_seq(r):
    return [p[0] + p[4] for p in r["p_sent"]]


def exp_seq(r):
    return [sum((j + 1) * p[j] for j in range(5)) / max(sum(p), 1e-12) for p in r["p_sent"]]


def binned(r, seq):
    rel = np.array(r["sent_tok"], float) / max(r["n_think_tok"], 1)
    b = np.minimum((rel * NB).astype(int), NB - 1)
    out = [None] * NB
    for k in range(NB):
        m = [x for x, bb in zip(seq, b) if bb == k]
        out[k] = float(np.mean(m)) if m else None
    return out


def onset_delta(r, key):
    pw = r[key]
    on = next((i for i, p in enumerate(pw) if p is not None and p >= 0.2), None)
    if on is None:
        return None, "none"
    e = ext_seq(r)
    before, after = e[:on + 1], e[on + 1:]
    if not after:
        return None, "at_end"
    return float(np.mean(after) - np.mean(before)), "ok"


def main():
    D = load()
    A = {ck: [r for r in D[ck]["rows"] if r["component"] == "A"] for ck in CKS}
    L = ["# M3: when is the answer settled, and does extremity build up during the deliberation?", "",
         "Generated by `exp/analysis/m3_summary.py` from the M3 shards on HF (`runs/M3/`). Registration: amendment 3 (M3), "
         "amendment 5 (trajectories, wrap-up onset, D analogue). Traces: valid B1 main-arm generations (A), frozen "
         "full-run D traces (o0, first 50 base items). Units: A wording (n ≤ 48), per-unit means over traces. CIs: "
         "percentile bootstrap over units (10,000, seed 20261024, per-label generator); two-sided Wilcoxon.", "",
         "## Traces", "", "| checkpoint | A traces | settled | mean think tokens | mean share after settle | "
         "settle point (tokens) |", "|---|---|---|---|---|---|"]
    U = {}
    for ck in CKS:
        rs = A[ck]
        st = lambda r: (r["sent_tok"][r["settle_sent"]] if r["settled"] and r["settle_sent"] is not None else None)  # noqa: E731
        U[ck] = {"share": by_unit(rs, lambda r: r["share_after"]),
                 "len": by_unit(rs, lambda r: float(r["n_think_tok"])),
                 "settle_tok": by_unit(rs, st),
                 "after_tok": by_unit(rs, lambda r: r["share_after"] * r["n_think_tok"]),
                 "settled": by_unit(rs, lambda r: float(bool(r["settled"])))}
        L.append(f"| {ck.upper()} | {len(rs)} | {np.mean([bool(r['settled']) for r in rs]):.3f} | "
                 f"{np.mean([r['n_think_tok'] for r in rs]):.0f} | {np.mean([r['share_after'] for r in rs]):.3f} | "
                 f"{np.mean([x for x in (st(r) for r in rs) if x is not None]):.0f} |")
    L += ["", "## Primary (amendment 3): settle point", "", "| quantity (RLVR − DPO, per wording) | estimate [95% CI] |", "|---|---|"]
    rs = C.paired(U["rlvr"]["share"], U["dpo"]["share"], "M3|share_after")
    L.append(f"| share of the trace after the settle point | {C.fmt(rs)} |")
    rt = C.paired(U["rlvr"]["settle_tok"], U["dpo"]["settle_tok"], "M3|settle_tok")
    L.append(f"| settle point, think tokens before it | {C.fmt(rt, 1)} |")
    us = sorted(set(U["rlvr"]["len"]) & set(U["dpo"]["len"]))
    ea = np.array([U["rlvr"]["after_tok"][u] - U["dpo"]["after_tok"][u] for u in us])
    et = np.array([U["rlvr"]["len"][u] - U["dpo"]["len"][u] for u in us])
    frac = float(ea.sum() / et.sum())
    idx = C.DI.make_rng("M3|extra_after").integers(0, len(us), size=(10000, len(us)))
    lo, hi = C.DI.percentile_ci(ea[idx].sum(1) / et[idx].sum(1))
    L.append(f"| share of RLVR's extra think tokens that come after the settle point (ratio of sums) | "
             f"{frac:.3f} [{lo:.3f}, {hi:.3f}], n = {len(us)} (registered: > 0.5) |")
    if rt["lo"] > 0 and hi < 0.5:
        h_settle = "failed, in the opposite direction (RLVR settles later; most of its extra tokens come before the settle point)"
    elif (rt["hi"] <= 0 or rt["lo"] < 0 < rt["hi"]) and lo > 0.5:
        h_settle = "result"
    else:
        h_settle = "no result"
    L += ["", "Probe accuracy (5-fold CV grouped by wording; majority baseline in brackets):", "",
          "| checkpoint | position | " + " | ".join(f"L{li}" for li in (4, 11, 15, 19, 23, 29)) + " |",
          "|---|---|" + "---|" * 6]
    for ck in CKS:
        pr = D[ck]["probes"]
        for pos in ("prompt_end", "think10", "think25", "think50"):
            if pos in pr:
                L.append(f"| {ck.upper()} | {pos} | " + " | ".join(f"{pr[pos][str(li)][0]:.3f} ({pr[pos][str(li)][1]:.3f})"
                                                                for li in (4, 11, 15, 19, 23, 29)) + " |")
    L += ["", "## (a′) Extremity trajectory over the think block (A)", "",
          "Mean P(1)+P(5) of the per-sentence readout in 10 bins of relative position (per wording, then mean).", "",
          "| bin | RLVR | DPO | SFT | RLVR − DPO [95% CI] |", "|---|---|---|---|---|"]
    T = {ck: collections.defaultdict(lambda: collections.defaultdict(list)) for ck in CKS}
    for ck in CKS:
        for r in A[ck]:
            for k, v in enumerate(binned(r, ext_seq(r))):
                if v is not None:
                    T[ck][k][r["id"]].append(v)
    TU = {ck: {k: {u: float(np.mean(v)) for u, v in T[ck][k].items()} for k in range(NB)} for ck in CKS}
    for k in range(NB):
        d = C.paired(TU["rlvr"][k], TU["dpo"][k], f"M3|traj|{k}")
        L.append(f"| {k * 10}–{k * 10 + 10}% | {np.mean(list(TU['rlvr'][k].values())):.3f} | "
                 f"{np.mean(list(TU['dpo'][k].values())):.3f} | {np.mean(list(TU['sft'][k].values())):.3f} | {C.fmt(d)} |")
    growth = {}
    for ck in CKS:
        g = {u: TU[ck][NB - 1][u] - TU[ck][0][u] for u in set(TU[ck][0]) & set(TU[ck][NB - 1])}
        growth[ck] = g
    rg = C.paired(growth["rlvr"], growth["dpo"], "M3|growth")
    L += ["", f"- Build-up within the trace (last bin − first bin), per checkpoint: "
          + "; ".join(f"{ck.upper()} {C.fmt(C.paired(growth[ck], {u: 0.0 for u in growth[ck]}, 'M3|growth|' + ck))}" for ck in CKS),
          f"- **RLVR − DPO difference in build-up: {C.fmt(rg)}**", ""]
    E = {ck: collections.defaultdict(lambda: collections.defaultdict(list)) for ck in CKS}
    for ck in CKS:
        for r in A[ck]:
            for k, v in enumerate(binned(r, exp_seq(r))):
                if v is not None:
                    E[ck][k][r["id"]].append(v)
    L += ["E[rating] trajectory (mean over wordings): " + "; ".join(
        f"{ck.upper()} " + " → ".join(f"{np.mean([np.mean(v) for v in E[ck][k].values()]):.2f}" for k in (0, 4, 9)) + " (bins 1, 5, 10)"
        for ck in CKS), ""]
    L += ["## (a″) Wrap-up onset and extremity after it (primary added test)", "",
          "| group | checkpoint | traces with onset | no onset | onset at the last sentence | mean onset position (share of trace) | "
          "mean ΔP(extreme) after − before |", "|---|---|---|---|---|---|---|"]
    res_on = {}
    for key, gname in (("p_wrapup_sent", "So/Therefore/Thus/Final"), ("p_wrapup_noso_sent", "without So")):
        Dl = {}
        for ck in CKS:
            cnt = collections.Counter()
            pos = []
            acc = collections.defaultdict(list)
            for r in A[ck]:
                dlt, why = onset_delta(r, key)
                cnt[why] += 1
                if dlt is not None:
                    acc[r["id"]].append(dlt)
                    on = next(i for i, p in enumerate(r[key]) if p is not None and p >= 0.2)
                    pos.append(r["sent_tok"][on] / max(r["n_think_tok"], 1))
            Dl[ck] = {u: float(np.mean(v)) for u, v in acc.items()}
            L.append(f"| {gname} | {ck.upper()} | {cnt['ok']} | {cnt['none']} | {cnt['at_end']} | "
                     f"{np.mean(pos) if pos else float('nan'):.2f} | {np.mean(list(Dl[ck].values())) if Dl[ck] else float('nan'):+.3f} |")
        res_on[gname] = C.paired(Dl["rlvr"], Dl["dpo"], f"M3|onset|{key}")
    L += ["", "| test (RLVR − DPO, per wording) | estimate [95% CI] | registered | verdict |", "|---|---|---|---|"]
    for gname, r in res_on.items():
        L.append(f"| ΔP(extreme) after − before onset, {gname} | {C.fmt(r)} | RLVR > DPO | {C.verdict(r, +1)} |")
    L += ["", "## D analogue (frozen D traces, letters A–E)", "", "| checkpoint | traces | mean P(max letter) bin 1 → bin 10 | "
          "mean P(final letter) bin 1 → bin 10 | settled | share after settle |", "|---|---|---|---|---|---|"]
    for ck in ("rlvr", "dpo"):
        rs = D.get(f"{ck}_D", {"rows": []})["rows"]
        if not rs:
            continue
        pm = [binned(r, [max(p) / max(sum(p), 1e-12) for p in r["p_sent"]]) for r in rs]
        labs = "ABCDE"
        pf = [binned(r, [p[labs.index(r["answer"])] / max(sum(p), 1e-12) for p in r["p_sent"]]) for r in rs if r["answer"] in labs]
        m = lambda X, k: np.mean([x[k] for x in X if x[k] is not None])  # noqa: E731
        L.append(f"| {ck.upper()} | {len(rs)} | {m(pm, 0):.3f} → {m(pm, NB - 1):.3f} | {m(pf, 0):.3f} → {m(pf, NB - 1):.3f} | "
                 f"{np.mean([bool(r['settled']) for r in rs]):.3f} | {np.mean([r['share_after'] for r in rs]):.3f} |")
    on1 = res_on["So/Therefore/Thus/Final"]
    L += ["", "## Verdict", "",
          f"- **M3-H (RLVR settles similar/earlier; > 50% of its extra tokens after the settle point): {h_settle}.** "
          f"Settle point RLVR − DPO {C.fmt(rt, 1)}; share of extra tokens after settle {frac:.3f} [{lo:.3f}, {hi:.3f}].",
          f"- **Extremity grows after the wrap-up onset more for RLVR (amendment 5): {C.verdict(on1, +1)}** "
          f"({C.fmt(on1)}); without So: {C.verdict(res_on['without So'], +1)} ({C.fmt(res_on['without So'])}).",
          f"- **Build-up of P(extreme) through the trace, RLVR − DPO (descriptive): {C.fmt(rg)}.**", "",
          "**Reading (not registered):** RLVR does not settle early and then pad. Most of its extra tokens (about two "
          "thirds) come *before* its answer settles, which is consistent with continued deliberation (F3). During that "
          "deliberation P(extreme) climbs steadily, and much more than DPO's: RLVR and DPO start close (+0.04 in the first "
          "tenth) and end far apart (+0.15 in the last tenth). The gap opens from the middle of the trace on, and grows "
          "more after the wrap-up onset. SFT is the most extreme throughout, as in B8. Probe accuracy at prompt end "
          "is low: above the majority baseline only for RLVR (0.39 vs 0.19 at L29), and below it for DPO. So the final "
          "answer is weakly decodable before the think block, and much of the extremity is built during it.", ""]
    out = C.ROOT / "results" / "sprint" / "M3"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
