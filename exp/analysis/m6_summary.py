"""M6 summary: representation similarity, linear CKA per layer (registration amendments 3, 13).

    python -m exp.analysis.m6_summary            -> results/sprint/M6/summary.md

Registered: DPO <-> RLVR CKA is lower on A than on D (B2's other-determinate cell) at layers 15-29, while SFT <-> DPO
shows no such A/D gap. Primary: the CKA difference A - D per layer and pair, with a bootstrap over prompts.

Storage defect: the M6 job wrote its rows with pa.Table.from_pylist, which takes the schema from the first row. The
per-set rows (no diff / ci_lo / ci_hi keys) came first, so the A - D rows lost those columns and only their (null)
cka survived. The bootstrap intervals are therefore not in the shard, and the residuals they were computed from were
on the sandbox's /tmp, which is gone. The A - D point estimates are recomputed here from the stored per-set CKA (the
job computed them the same way: cka(A) - cka(other_det)). Without intervals the registered test cannot be run.
"""
import sys

from . import sprint_common as C

PAIRS = (("dpo-rlvr", "DPO ↔ RLVR"), ("sft-dpo", "SFT ↔ DPO"))
POS = (("pe", "last prompt token"), ("th", "first 64 think tokens"))
SETS = ("A", "self_det", "other_indet", "other_det")
LATE = (15, 19, 23, 29)


def main():
    f = C.fetch("runs/M6/")[0]
    rows = C.read(f)
    cka = {(r["pair"], r["position"], r["layer"], r["set"]): r["cka"] for r in rows if r["set"] != "A-D"}
    layers = sorted({r["layer"] for r in rows})
    diff = {(p, pos, li): cka[(p, pos, li, "A")] - cka[(p, pos, li, "other_det")]
            for p, _ in PAIRS for pos, _ in POS for li in layers}
    L = ["# M6: representation similarity (linear CKA)", "",
         "Generated by `exp/analysis/m6_summary.py` from the M6 shard on HF (`runs/M6/ladder/`). Registration: "
         "amendment 3 (M6), amendment 13 (inputs, positions, primary). Sets: 48 A wordings; B2 self-determinate, "
         "other-indeterminate and other-determinate (= D) cells, 40 each. SFT uses the DPO system prompt; the 64 think "
         "tokens are DPO's greedy continuation, teacher-forced into all three models.", "",
         "**Registered test not computable.** The job's shard writer took the column set from the first row, so the "
         "A − D rows lost their difference and bootstrap-interval columns (see the module docstring and the disclosure "
         "ledger). The residuals were on the sandbox and are gone. The A − D differences below are point estimates "
         "recomputed from the stored per-set CKA; no interval is available.", "",
         "## A − D CKA difference (point estimates)", "",
         "| pair | position | " + " | ".join(f"L{li}" for li in layers) + " |",
         "|---|---|" + "---|" * len(layers)]
    for p, pn in PAIRS:
        for pos, posn in POS:
            L.append(f"| {pn} | {posn} | " + " | ".join(f"{diff[(p, pos, li)]:+.4f}" for li in layers) + " |")
    pe = {p: [diff[(p, "pe", li)] for li in LATE] for p, _ in PAIRS}
    L += ["", "Mean A − D at layers 15–29, last prompt token: "
              f"DPO ↔ RLVR {sum(pe['dpo-rlvr']) / 4:+.4f}, SFT ↔ DPO {sum(pe['sft-dpo']) / 4:+.4f}.", "",
          "Reading (descriptive, no interval): at the last prompt token both pairs are less similar on A than on D in "
          "layers 15–29, and by about the same amount. The hypothesis needs the gap in DPO ↔ RLVR **and not** in "
          "SFT ↔ DPO; the point estimates show it in both, so they do not support an RLVR-specific A/D difference. "
          "The lower A similarity looks like a property of the A set at every post-SFT step, not of RLVR. Over the "
          "think tokens all CKAs are above 0.96 and the A − D differences are near 0 (largest +0.016, SFT ↔ DPO "
          "at layer 29, in the opposite direction).", "",
          "## CKA per set (descriptive)", ""]
    for pos, posn in POS:
        L += [f"### {posn}", "", "| pair | set | " + " | ".join(f"L{li}" for li in layers) + " |",
              "|---|---|" + "---|" * len(layers)]
        for p, pn in PAIRS:
            for s in SETS:
                L.append(f"| {pn} | {s} | " + " | ".join(f"{cka[(p, pos, li, s)]:.4f}" for li in layers) + " |")
        L.append("")
    out = C.ROOT / "results" / "sprint" / "M6"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
