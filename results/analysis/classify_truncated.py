"""EXPLORATORY (plan s7; not pre-registered, changes no pre-registered number).

Classifies every row with status == "truncated" in the three full-run files as a verbatim repetition loop or not, using a
simple repetition heuristic on the raw generation, and writes results/analysis/exploratory_truncation.md.

Standalone: reads the three JSON files directly and imports neither metrics.py nor stats.py.
Run from the repo root:  python results/analysis/classify_truncated.py
"""
import collections
import json
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "analysis" / "exploratory_truncation.md"
CKPTS = ["sft", "dpo", "rlvr"]

# Heuristic (thresholds fixed after looking at the 23 rows: the loop rows and the others are separated by a wide gap,
# see the table; they were not tuned to hit a target count).
TAIL_CHARS = 3000      # compression ratio of the last 3000 characters (zlib level default): repetitive text compresses well
WORDS = 400            # unique 6-gram share over the last 400 words
LOOP_COMPRESSION_MAX = 0.25
LOOP_UNIQUE_6GRAM_MAX = 0.70
QUOTE_CHARS = 220


def metrics(text):
    tail = text[-TAIL_CHARS:]
    comp = len(zlib.compress(tail.encode("utf-8"))) / max(1, len(tail.encode("utf-8")))
    w = text.split()[-WORDS:]
    grams = [" ".join(w[i:i + 6]) for i in range(len(w) - 5)]
    uniq = len(set(grams)) / max(1, len(grams))
    return comp, uniq


def classify(text, comp, uniq):
    if comp < LOOP_COMPRESSION_MAX and uniq < LOOP_UNIQUE_6GRAM_MAX:
        return "repetition loop"
    if "</think>" in text:
        return "other (truncated after the reasoning block closed)"
    return "long reasoning cut mid-thought"


def main():
    rows = []
    for cp in CKPTS:
        d = json.load(open(ROOT / "results" / f"full_run_{cp}" / f"full_run_{cp}.json", encoding="utf-8"))["rows"]
        for r in d:
            if r["status"] == "truncated":
                comp, uniq = metrics(r["raw_output"])
                rows.append({"ckpt": cp.upper(), "component": r["component"], "id": r["id"], "seed": r["seed"],
                             "n_tokens": r["n_tokens"], "chars": len(r["raw_output"]), "comp": comp, "uniq": uniq,
                             "cls": classify(r["raw_output"], comp, uniq), "tail": r["raw_output"][-QUOTE_CHARS:]})
    cats = ["repetition loop", "long reasoning cut mid-thought", "other (truncated after the reasoning block closed)"]
    count = collections.Counter((r["ckpt"], r["component"], r["cls"]) for r in rows)
    L = ["# Exploratory: classification of truncated generations", "",
         "**EXPLORATORY (plan s7). Not pre-registered. This changes no pre-registered number and nothing here enters the scorecard.**",
         "Generated by `results/analysis/classify_truncated.py` from `results/full_run_{sft,dpo,rlvr}/*.json`.", "",
         f"All {len(rows)} rows with status `truncated` across the three checkpoints (every component, including E).", "",
         "## Result", "",
         "**The four repetition loops are all SFT. RLVR has none** (nor does DPO).", "",
         "| checkpoint | component | rows | " + " | ".join(cats) + " |", "|---|---|---|---|---|---|"]
    for cp in [c.upper() for c in CKPTS]:
        for comp in "ABCDE":
            n = sum(count[(cp, comp, c)] for c in cats)
            if n:
                L.append(f"| {cp} | {comp} | {n} | " + " | ".join(str(count[(cp, comp, c)]) for c in cats) + " |")
    L.append("")
    L.append("| checkpoint | truncated rows | " + " | ".join(cats) + " |")
    L.append("|---|---|---|---|---|")
    for cp in [c.upper() for c in CKPTS]:
        n = sum(1 for r in rows if r["ckpt"] == cp)
        L.append(f"| {cp} | {n} | " + " | ".join(str(sum(1 for r in rows if r["ckpt"] == cp and r["cls"] == c)) for c in cats) + " |")
    L += ["", "RLVR's 13 rows are the 12 in components A to D (A 5, B 1, C 3, D 3) plus E_46 (component E, cap 16000).", "",
          "## Heuristic and thresholds", "",
          f"- Compression ratio: `len(zlib.compress(last {TAIL_CHARS} characters)) / len(last {TAIL_CHARS} characters)` (UTF-8 bytes). "
          "Repetitive text compresses well, so a low ratio means a loop.",
          f"- Unique 6-gram share: distinct 6-word windows divided by all 6-word windows over the last {WORDS} words. "
          "A verbatim loop reuses the same windows, so the share is low.",
          f"- **Loop** if compression ratio < {LOOP_COMPRESSION_MAX} **and** unique 6-gram share < {LOOP_UNIQUE_6GRAM_MAX}. "
          "Otherwise **long reasoning cut mid-thought**; **other** if the text already contains `</think>` (none do).",
          "- The thresholds were fixed after looking at these 23 rows. The loop rows and the rest are separated by a wide gap "
          "(see the table below: loops have ratio <= 0.204 and share <= 0.565; every other row has ratio >= 0.268 and share >= 0.937), "
          "so the classification does not hinge on the exact cut-offs, but they were set post hoc on the same rows they classify.", "",
          "## Caveat", "",
          "I read only the **tails** (the last ~220 characters, quoted below) of each row, not the full texts. The loop calls rest on the "
          "heuristic plus those tails. For the non-loop rows, \"long reasoning cut mid-thought\" means: no repetition signature and the "
          "tail is mid-sentence reasoning. It does **not** establish that a higher cap would have produced an answer.", "",
          "## Per-row metrics", "",
          "| checkpoint | id | seed | tokens | chars | compression ratio | unique 6-gram share | class |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['ckpt']} | {r['id']} | {r['seed']} | {r['n_tokens']} | {r['chars']} | {r['comp']:.3f} | {r['uniq']:.3f} | {r['cls']} |")
    L += ["", "## Quoted tails (last ~220 characters of the raw generation, shown as Python string literals)", ""]
    for r in rows:
        L.append(f"- **{r['ckpt']} {r['id']}** (seed {r['seed']}, {r['cls']}): `{r['tail']!r}`".replace("\n", " "))
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT, "| rows", len(rows), dict(collections.Counter((r["ckpt"], r["cls"]) for r in rows)))
    # self-check of the plain statement in the text above
    assert all(r["ckpt"] == "SFT" for r in rows if r["cls"] == "repetition loop") and sum(r["cls"] == "repetition loop" for r in rows) == 4


if __name__ == "__main__":
    sys.exit(main())
