"""EXPLORATORY (plan s7; not pre-registered, changes no pre-registered number).

Part 2 (artifact checks 1-5) and Part 3 (breakdowns 6-10) of the component A length result. Writes
results/analysis/exploratory_length.md (item 11, the qualitative reading, is hand-written in
exploratory_length_item11.md and appended). If any of checks 1-5 fails, the script writes the failure and STOPS before Part 3 (exit code 2).

Standalone: reads the three full-run JSON files, the item files, the run logs and docs/checkpoint_map.md directly.
It imports neither metrics.py nor stats.py. Run from the repo root:  python results/analysis/length_checks.py
"""
import collections
import csv
import json
import re
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "analysis" / "exploratory_length.md"
ITEM11 = ROOT / "results" / "analysis" / "exploratory_length_item11.md"    # hand-written; appended at the end
CK = ["sft", "dpo", "rlvr"]
REPO = {"sft": "allenai/Olmo-3-7B-Think-SFT", "dpo": "allenai/Olmo-3-7B-Think-DPO", "rlvr": "allenai/Olmo-3-7B-Think"}
CAP = {"A": 4000, "B": 4000, "C": 4000, "D": 4000, "E": 16000}
L = []


def w(s=""):
    L.append(s)


def load():
    rows = {}
    for cp in CK:
        rows[cp] = json.load(open(ROOT / "results" / f"full_run_{cp}" / f"full_run_{cp}.json", encoding="utf-8"))["rows"]
    return rows


def med(x):
    return float(np.median(np.asarray(x, float)))


def f(x, nd=3):
    return "nan" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


# --------------------------------------------------------------------------------------------- units (independent code)
def items():
    A = json.load(open(ROOT / "items" / "items_A_selfreport.json", encoding="utf-8"))["items"]
    D = json.load(open(ROOT / "items" / "items_D_csqa.json", encoding="utf-8"))["items"]
    return A, D


def a_units(rows, A, include_truncated_at_cap=False, seeds=None):
    """{wording_id: mean tokens over the checkpoint's valid (or valid + truncated-at-cap) rows of that wording}."""
    acc = collections.defaultdict(list)
    for r in rows:
        if r["component"] != "A":
            continue
        if seeds is not None and r["seed"] not in seeds:
            continue
        if r["status"] == "valid" or (include_truncated_at_cap and r["status"] == "truncated"):
            acc[r["id"]].append(r["n_tokens"] if r["status"] == "valid" else CAP["A"])
    return {k: float(np.mean(v)) for k, v in acc.items()}


def paired_diff(ua, ub, ids):
    keys = [k for k in ids if k in ua and k in ub]
    return keys, np.array([ua[k] - ub[k] for k in keys])


def all_units(rows, A, D):
    """{component: {unit: mean tokens}} for valid rows: A per wording; B, C, E per item; D per base item, both orders valid."""
    base = {it["id"]: it["draw_index"] for it in D}
    n_orders = collections.Counter(it["draw_index"] for it in D)
    acc = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows:
        if r["status"] != "valid":
            continue
        c = r["component"]
        key = base[r["id"]] if c == "D" else r["id"]
        acc[c][key].append(r["n_tokens"])
    out = {}
    for c, d in acc.items():
        out[c] = {k: float(np.mean(v)) for k, v in d.items() if c != "D" or len(v) == n_orders[k]}
    return out


def table3_value(comparison, probe):
    for r in csv.DictReader(open(ROOT / "results" / "analysis" / "table3_comparison.csv", encoding="utf-8")):
        if r["comparison"] == comparison and r["probe"] == probe:
            return float(r["diff"])
    return None


def main():
    rows = load()
    A, D = items()
    a_ids = [it["id"] for it in A]
    ok_all = True
    w("# Exploratory: verification and breakdowns of the component A length result")
    w()
    w("**EXPLORATORY (plan s7). Not pre-registered. This changes no pre-registered number and nothing here enters the scorecard.**")
    w("Generated by `results/analysis/length_checks.py` (standalone: no import of `metrics.py` or `stats.py`). "
      "Part 2 (checks 1-5) is first; Part 3 (items 6-10) runs only if all of checks 1-5 pass. Item 11 (qualitative, hand-written) is appended at the end.")
    w()
    w("# Part 2: artifact checks")
    w()

    # ---- 1. batch padding
    w("## Check 1. Rows sharing a batch_index have distinct n_tokens?")
    w()
    w("| checkpoint | batches | batches with a duplicate n_tokens | of which duplicates are only rows at the token cap | batches where ALL rows are identical |")
    w("|---|---|---|---|---|")
    uniform_total = 0
    dup_detail = {}
    for cp in CK:
        by = collections.defaultdict(list)
        for r in rows[cp]:
            by[r["batch_index"]].append(r)
        n_dup = n_dup_cap_only = n_uniform = 0
        for b, rr in by.items():
            toks = [r["n_tokens"] for r in rr]
            cnt = collections.Counter(toks)
            dups = {t for t, c in cnt.items() if c > 1}
            if dups:
                n_dup += 1
                if all(t == CAP[rr[0]["component"]] for t in dups):
                    n_dup_cap_only += 1
                else:
                    dup_detail.setdefault(cp, []).append((b, rr[0]["component"], sorted(dups)))
            if len(rr) > 1 and len(set(toks)) == 1:
                n_uniform += 1
        uniform_total += n_uniform
        w(f"| {cp.upper()} | {len(by)} | {n_dup} | {n_dup_cap_only} | {n_uniform} |")
    w()
    for cp, lst in dup_detail.items():
        w(f"- {cp.upper()} batches with duplicate n_tokens values that are NOT the cap (batch, component, duplicated values): "
          + "; ".join(f"{b} {c} {v}" for b, c, v in lst))
    w()
    c1 = uniform_total == 0
    w(f"**Check 1: {'PASS' if c1 else 'FAIL'}** (no batch has all rows identical)" if c1 else "**Check 1: FAIL: a uniform batch exists. STOP.**")
    ok_all &= c1
    w()

    # ---- 2. n_tokens = generated tokens only
    w("## Check 2. n_tokens is generated tokens only (not prompt + generated)?")
    w()
    w("No tokenizer is available locally, so the check is by consequence, not by re-tokenising: "
      "(a) if n_tokens included the prompt, rows that hit the cap (max_new_tokens) would show cap + prompt_tokens; "
      "(b) the characters per n_tokens of the generation should be near English text's ratio, not inflated by the prompt.")
    w()
    w("| checkpoint | rows | max n_tokens / cap, A-D (cap 4000) | rows with n_tokens > cap | min prompt_tokens | median prompt_tokens | cap rows with n_tokens == cap |")
    w("|---|---|---|---|---|---|---|")
    c2 = True
    for cp in CK:
        rr = rows[cp]
        over = sum(1 for r in rr if r["n_tokens"] > r["max_new_tokens"])
        capr = [r for r in rr if r["hit_cap"]]
        eq = sum(1 for r in capr if r["n_tokens"] == r["max_new_tokens"])
        mx = max(r["n_tokens"] for r in rr if r["component"] in "ABCD")
        pt = [r["prompt_tokens"] for r in rr]
        w(f"| {cp.upper()} | {len(rr)} | {mx} | {over} | {min(pt)} | {med(pt):.0f} | {eq} of {len(capr)} |")
        c2 &= over == 0 and eq == len(capr)
    w()
    w("Characters per token of the raw generation, for the first row of each checkpoint in components A, B, D, E and the last cap row "
      "(prompt_tokens shown to compare):")
    w()
    w("| checkpoint | id | seed | n_tokens | prompt_tokens | chars of raw_output | chars per n_tokens |")
    w("|---|---|---|---|---|---|---|")
    ratios = []
    for cp in CK:
        pick = []
        for c in "ABDE":
            pick.append(next(r for r in rows[cp] if r["component"] == c and r["status"] == "valid"))
        capr = [r for r in rows[cp] if r["hit_cap"]]
        if capr:
            pick.append(capr[-1])
        for r in pick:
            cpt = len(r["raw_output"]) / r["n_tokens"]
            w(f"| {cp.upper()} | {r['id']} | {r['seed']} | {r['n_tokens']} | {r['prompt_tokens']} | {len(r['raw_output'])} | {cpt:.2f} |")
    for cp in CK:
        ratios += [len(r["raw_output"]) / r["n_tokens"] for r in rows[cp] if r["n_tokens"] > 0]
    w()
    w(f"Over all {len(ratios)} rows, chars per n_tokens: min {min(ratios):.2f}, median {med(ratios):.2f}, max {max(ratios):.2f}.")
    c2 &= min(ratios) > 1.5 and max(ratios) < 8
    w()
    w(f"**Check 2: {'PASS' if c2 else 'FAIL'}.** No row exceeds its cap, every cap row has n_tokens exactly equal to the cap while "
      f"prompt_tokens is >= {min(r['prompt_tokens'] for cp in CK for r in rows[cp])} for every row, so the prompt is not included. "
      "This is an inference from the cap, not a re-tokenisation.")
    ok_all &= c2
    w()

    # ---- 3. hit_eos / hit_cap
    w("## Check 3. hit_eos and hit_cap against the cap")
    w()
    w("| checkpoint | rows | hit_cap rows | hit_cap with n_tokens == cap | hit_cap with n_tokens != cap | hit_eos rows | hit_eos with n_tokens == cap | rows with neither | rows with both |")
    w("|---|---|---|---|---|---|---|---|---|")
    c3 = True
    for cp in CK:
        rr = rows[cp]
        cap_r = [r for r in rr if r["hit_cap"]]
        eos_r = [r for r in rr if r["hit_eos"]]
        a = sum(r["n_tokens"] == r["max_new_tokens"] for r in cap_r)
        b = sum(r["n_tokens"] == r["max_new_tokens"] for r in eos_r)
        neither = sum(1 for r in rr if not r["hit_cap"] and not r["hit_eos"])
        both = sum(1 for r in rr if r["hit_cap"] and r["hit_eos"])
        w(f"| {cp.upper()} | {len(rr)} | {len(cap_r)} | {a} | {len(cap_r) - a} | {len(eos_r)} | {b} | {neither} | {both} |")
        c3 &= a == len(cap_r) and b == 0 and both == 0
        # also: every row whose n_tokens equals its cap has hit_cap
        c3 &= all(r["hit_cap"] for r in rr if r["n_tokens"] == r["max_new_tokens"])
    w()
    w(f"**Check 3: {'PASS' if c3 else 'FAIL'}.** (also checked: every row with n_tokens equal to its cap has hit_cap set.)")
    ok_all &= c3
    w()

    # ---- 4. independent recomputation
    w("## Check 4. Independent recomputation of the RLVR - DPO component A median paired difference")
    w()
    ua_r = a_units(rows["rlvr"], A)
    ua_d = a_units(rows["dpo"], A)
    keys, diffs = paired_diff(ua_r, ua_d, a_ids)
    mine = med(diffs)
    table = table3_value("RLVR-DPO", "Reasoning length A")
    w(f"Unit = wording (48), per-checkpoint value = mean n_tokens over that wording's valid generations, a wording enters if it has >= 1 valid "
      f"generation in both checkpoints (here {len(keys)} of 48), statistic = median over wordings of (RLVR - DPO).")
    w()
    w(f"- This script: **{mine!r}** (n = {len(keys)})")
    w(f"- `results/analysis/table3_comparison.csv`: **{table!r}**")
    # table3_comparison.csv stores diffs rounded to 4 decimals, so compare at that precision; the full-precision value is 1732/3
    c4 = abs(mine - 1732 / 3) < 1e-9 and table is not None and abs(round(mine, 4) - table) < 1e-9
    w(f"- Full-precision value equals 1732/3 = {1732 / 3!r} (difference {abs(mine - 1732 / 3):.1e}); rounded to the CSV's 4 decimals it equals the "
      f"committed table value (CSV stores 4 decimals, so the unrounded difference to the CSV is {abs(mine - table):.1e}, rounding only).")
    w(f"- Match to 577.333 and to the committed table: **{'exact' if c4 else 'NO'}**")
    w()
    w(f"**Check 4: {'PASS' if c4 else 'FAIL'}.**")
    ok_all &= c4
    w()

    # ---- 5. revisions
    w("## Check 5. Model revisions: three distinct SHAs, each matching docs/checkpoint_map.md")
    w()
    cmap = (ROOT / "docs" / "checkpoint_map.md").read_text(encoding="utf-8")
    w("| checkpoint | repo (run log) | sha in run log | hub confirms same | repo's main commit in checkpoint_map.md | match |")
    w("|---|---|---|---|---|---|")
    shas = {}
    c5 = True
    for cp in CK:
        log = (ROOT / "results" / f"full_run_{cp}" / f"full_run_{cp}.log").read_text(encoding="utf-8", errors="replace")
        m = re.search(r"repo (\S+) sha ([0-9a-f]{40}) \| hub confirms revision: ([0-9a-f]{40})", log)
        repo, sha, hub = m.group(1), m.group(2), m.group(3)
        mm = re.search(r"\| `" + re.escape(repo) + r"` \| `([0-9a-f]{40})`", cmap)
        mapped = mm.group(1) if mm else None
        shas[cp] = sha
        ok = repo == REPO[cp] and sha == hub and sha == mapped
        c5 &= ok
        w(f"| {cp.upper()} | `{repo}` | `{sha}` | {'yes' if sha == hub else 'NO'} | `{mapped}` | {'yes' if ok else 'NO'} |")
    c5 &= len(set(shas.values())) == 3
    w()
    w(f"Distinct SHAs: {len(set(shas.values()))} of 3. Each row's `sha` field in the result JSON also equals its log SHA: "
      + str(all(all(r['sha'] == shas[cp] for r in rows[cp]) for cp in CK)) + ".")
    w()
    w(f"**Check 5: {'PASS' if c5 else 'FAIL'}.**")
    ok_all &= c5
    w()
    w("## Summary of checks 1-5")
    w()
    w(f"Check 1 {'PASS' if c1 else 'FAIL'}; Check 2 {'PASS' if c2 else 'FAIL'}; Check 3 {'PASS' if c3 else 'FAIL'}; "
      f"Check 4 {'PASS' if c4 else 'FAIL'}; Check 5 {'PASS' if c5 else 'FAIL'}.")
    w()
    w("Note on the script's history: the first version compared the recomputed 577.3333333333333 with the CSV's 577.3333 at a tolerance of 1e-9, "
      "which flagged check 4 (and the A and A-D rows of item 9) as failing by 3e-05. That was a rounding artefact of the CSV's 4 decimals, "
      "not a discrepancy; the comparison was changed to the CSV's precision and the script re-run. No data or other check was changed.")
    w()
    if not ok_all:
        w("**At least one check failed. STOPPED before Part 3.**")
        OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
        print("CHECK FAILED; see", OUT)
        return 2

    # ============================================================================================ Part 3
    w("# Part 3: breakdowns of the component A length result (RLVR - DPO unless stated)")
    w()
    trait = {it["id"]: it["trait"] for it in A}
    key = {it["id"]: it["key"] for it in A}
    orig = {it["id"]: it["original"] for it in A}

    # ---- 6. per trait
    w("## Item 6. Per trait (6 wordings each): median paired difference RLVR - DPO")
    w()
    w("| trait | n wordings | median paired diff | wordings with RLVR > DPO | per-wording differences (wording index 0..5) |")
    w("|---|---|---|---|---|")
    traits = sorted({trait[k] for k in a_ids})
    n_pos_traits = 0
    for t in traits:
        ids = [k for k in a_ids if trait[k] == t]
        kk, dd = paired_diff(ua_r, ua_d, ids)
        n_pos_traits += med(dd) > 0
        w(f"| {t} | {len(kk)} | {med(dd):.1f} | {int((dd > 0).sum())} of {len(kk)} | " + ", ".join(f"{x:.0f}" for x in dd) + " |")
    w()
    w(f"Traits with a positive per-trait median: {n_pos_traits} of {len(traits)}. Wordings with RLVR > DPO overall: "
      f"{int((diffs > 0).sum())} of {len(diffs)}.")
    w()

    # ---- 7. wording type
    w("## Item 7. By wording type (positive-keyed vs reverse-keyed)")
    w()
    w("`key` in `items/items_A_selfreport.json`: +1 positive-keyed (agreeing expresses the trait), -1 reverse-keyed.")
    w()
    w("| wording type | n wordings | median paired diff | wordings with RLVR > DPO |")
    w("|---|---|---|---|")
    for name, sel in [("positive-keyed (key = +1)", lambda k: key[k] == 1), ("reverse-keyed (key = -1)", lambda k: key[k] == -1),
                      ("original wording (original = true)", lambda k: orig[k]), ("non-original wordings", lambda k: not orig[k])]:
        kk, dd = paired_diff(ua_r, ua_d, [k for k in a_ids if sel(k)])
        w(f"| {name} | {len(kk)} | {med(dd):.1f} | {int((dd > 0).sum())} of {len(kk)} |")
    w()

    # ---- 8. per seed
    w("## Item 8. Within each seed separately (one generation per wording per checkpoint; wording enters if valid in both)")
    w()
    w("| seed | n wordings | median paired diff | wordings with RLVR > DPO | descriptive median RLVR / DPO (valid rows of that seed) |")
    w("|---|---|---|---|---|")
    for s in (0, 1, 2):
        ur = a_units(rows["rlvr"], A, seeds={s})
        ud = a_units(rows["dpo"], A, seeds={s})
        kk, dd = paired_diff(ur, ud, a_ids)
        mr = med([r["n_tokens"] for r in rows["rlvr"] if r["component"] == "A" and r["seed"] == s and r["status"] == "valid"])
        md = med([r["n_tokens"] for r in rows["dpo"] if r["component"] == "A" and r["seed"] == s and r["status"] == "valid"])
        w(f"| {s} | {len(kk)} | {med(dd):.1f} | {int((dd > 0).sum())} of {len(kk)} | {mr:.1f} / {md:.1f} |")
    w()

    # ---- 9. side by side
    w("## Item 9. Difference of marginal medians vs median of paired differences, every length row")
    w()
    w("Marginal = median over valid rows (generations) per checkpoint, difference of the two checkpoints' medians. "
      "Paired = median over pairing units of the per-unit difference (the pre-registered quantity). "
      "Pooled A-D marginal = median over valid rows of A-D; pooled paired = units of A, B, C, D concatenated. "
      "Paired values recomputed here are compared with `table3_comparison.csv`.")
    w()
    units = {cp: all_units(rows[cp], A, D) for cp in CK}
    w("| comparison | row | marginal median (a) | marginal median (b) | diff of marginal medians | median of paired diffs (recomputed) | table3 value | match | paired n |")
    w("|---|---|---|---|---|---|---|---|---|")
    all_match = True
    for cmp_name, ca, cb in [("RLVR-DPO", "rlvr", "dpo"), ("DPO-SFT", "dpo", "sft")]:
        pooled_d = []
        for comp in list("ABCDE") + ["A-D"]:
            comps = list(comp) if comp != "A-D" else list("ABCD")
            ma = med([r["n_tokens"] for r in rows[ca] if r["component"] in comps and r["status"] == "valid"])
            mb = med([r["n_tokens"] for r in rows[cb] if r["component"] in comps and r["status"] == "valid"])
            dd = []
            for c in comps:
                ks = [k for k in units[ca][c] if k in units[cb][c]]
                dd += [units[ca][c][k] - units[cb][c][k] for k in ks]
            pm = med(dd)
            tv = table3_value(cmp_name, "Reasoning length " + comp)
            ok = tv is not None and abs(tv - round(pm, 4)) < 1e-9     # the CSV stores 4 decimals
            all_match &= ok
            w(f"| {cmp_name} | {comp} | {ma:.1f} | {mb:.1f} | {ma - mb:.1f} | {pm:.3f} | {f(tv)} | {'yes' if ok else 'NO'} | {len(dd)} |")
    w()
    w(f"All recomputed paired values equal the committed table 3: **{all_match}**.")
    w()
    w("### Why A shows 410 (marginal) against 577.333 (paired)?")
    w()
    rv = np.array([ua_r[k] for k in keys])
    dp = np.array([ua_d[k] for k in keys])
    row_r = [r["n_tokens"] for r in rows["rlvr"] if r["component"] == "A" and r["status"] == "valid"]
    row_d = [r["n_tokens"] for r in rows["dpo"] if r["component"] == "A" and r["status"] == "valid"]
    ratio = rv / dp
    q = lambda x, p: float(np.percentile(x, p))
    w(f"- Marginal medians over valid rows: RLVR {med(row_r):.1f} (n = {len(row_r)}), DPO {med(row_d):.1f} (n = {len(row_d)}): difference {med(row_r) - med(row_d):.1f}.")
    w(f"- Median over the 48 wordings of the wording means: RLVR {med(rv):.1f}, DPO {med(dp):.1f}: difference {med(rv) - med(dp):.1f}.")
    w(f"- Median of the per-wording differences: {med(diffs):.1f}; mean of the per-wording differences: {diffs.mean():.1f}; "
      f"quartiles of the per-wording differences: {q(diffs, 25):.1f}, {q(diffs, 50):.1f}, {q(diffs, 75):.1f} (min {diffs.min():.1f}, max {diffs.max():.1f}).")
    w(f"- Median per-wording ratio RLVR / DPO: {med(ratio):.2f} (quartiles {q(ratio, 25):.2f}, {q(ratio, 75):.2f}).")
    w(f"- Wording means: DPO quartiles {q(dp, 25):.0f} / {q(dp, 50):.0f} / {q(dp, 75):.0f}; RLVR quartiles {q(rv, 25):.0f} / {q(rv, 50):.0f} / {q(rv, 75):.0f}. "
      f"Correlation between a wording's DPO mean and its RLVR mean: {np.corrcoef(dp, rv)[0, 1]:.2f}; correlation between DPO mean and the difference: {np.corrcoef(dp, diffs)[0, 1]:.2f}.")
    w(f"- Row level (valid generations): RLVR mean {np.mean(row_r):.1f} vs median {med(row_r):.1f}; DPO mean {np.mean(row_d):.1f} vs median {med(row_d):.1f}. "
      f"Mean of the 48 wording means: RLVR {rv.mean():.1f}, DPO {dp.mean():.1f}.")
    w(f"- Share of generations above 2000 tokens (valid rows): RLVR {np.mean(np.array(row_r) > 2000):.3f}, DPO {np.mean(np.array(row_d) > 2000):.3f}; "
      f"75th percentile of row-level tokens: RLVR {q(row_r, 75):.0f}, DPO {q(row_d, 75):.0f}.")
    # numeric decomposition: how much of the gap is due to unit (wording mean vs row) vs median-of-differences
    w(f"- Decomposition: 410.0 (row-level marginal) -> {med(rv) - med(dp):.1f} (difference of medians of wording means: effect of averaging over seeds and weighting wordings equally) "
      f"-> {med(diffs):.1f} (median of paired differences: effect of pairing).")
    w()

    # ---- 10. censoring
    w("## Item 10. Censoring bound: truncated rows included at the cap (4000) instead of excluded")
    w()
    tr = {cp: sum(1 for r in rows[cp] if r["component"] == "A" and r["status"] == "truncated") for cp in CK}
    other_invalid = {cp: [(r["id"], r["seed"], r["status"]) for r in rows[cp] if r["component"] == "A" and r["status"] not in ("valid", "truncated")] for cp in CK}
    w(f"Truncated A rows: SFT {tr['sft']}, DPO {tr['dpo']}, RLVR {tr['rlvr']}. Non-valid, non-truncated A rows (still excluded): "
      + "; ".join(f"{cp.upper()}: {v}" for cp, v in other_invalid.items() if v) + ".")
    w()
    w("A truncated generation is right-censored (its true length is at least the cap), so including it at 4000 gives a **lower bound** on that unit's length.")
    w()
    w("| comparison | n wordings (excluded) | median paired diff, truncated excluded | n (included at cap) | median paired diff, truncated included at 4000 | change |")
    w("|---|---|---|---|---|---|")
    for cmp_name, ca, cb in [("RLVR - DPO", "rlvr", "dpo"), ("DPO - SFT", "dpo", "sft")]:
        e1 = paired_diff(a_units(rows[ca], A), a_units(rows[cb], A), a_ids)
        e2 = paired_diff(a_units(rows[ca], A, True), a_units(rows[cb], A, True), a_ids)
